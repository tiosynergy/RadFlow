import { defineConfig } from "vitest/config";
import { fileURLToPath } from "url";
import { dirname, resolve } from "path";

const root = dirname(fileURLToPath(import.meta.url));

/* Тести — лише на ЧИСТУ логіку (lib/*): сітка слотів, графік кабінету, похідні
   статуси, колізії, пріоритети. Саме там живуть правила, які найдорожче ламати
   (запис пацієнта в закритий кабінет / у минуле / поверх іншого), і саме їх
   найважче перевірити руками. Компоненти й БД тут НЕ тестуємо — для них
   лишається `npm run typecheck` + ручний прогін на сіді.

   Виняток (аудит с45): роути публікованої доступності перевіряються
   ПОВЕДІНКОВО — з підробленим Supabase-клієнтом у памʼяті, без мережі й
   Postgres (tests/slotsRoute.test.ts). Причина: дірка I-1 («кабінет у ремонті
   публікується вільним») жила саме в роуті, а не в lib/*, і статичні
   grep-перевірки лишалися зеленими на зламаному запиті. */
export default defineConfig({
  resolve: {
    alias: { "@": resolve(root, ".") },
  },
  /* с48 (U-30): автоматичний JSX-рантайм — те саме, що робить Next. Без нього
     esbuild компілює JSX у `React.createElement`, а в компонентах проєкту
     `import React` немає (Next його підставляє сам) — тож будь-яка спроба
     ВИКЛИКАТИ компонент із тесту падала на `React is not defined`.
     Це не «включаємо компонентні тести»: DOM тут як не було, так і немає.
     Це дозволяє перевіряти компоненти-чисті-функції по ПОВЕРНУТОМУ ДЕРЕВУ —
     єдиний спосіб, яким сторож не обходиться раннім `return` (ревʼю U-30). */
  esbuild: { jsx: "automatic" },
  test: {
    environment: "node",
    /* ⚠️ `.test.tsx` теж: відколи JSX-рантайм увімкнений (нижче), наступний
       автор природно назве компонентний тест `*.test.tsx` — і без цього рядка
       він просто НЕ ЗАПУСТИТЬСЯ, показавши «0 failed» замість «не запущено»
       (ревʼю U-30, с48). Пара «esbuild дозволив / include заборонив» — тиха. */
    include: ["tests/**/*.test.ts", "tests/**/*.test.tsx"],
    /* Зона НЕ UTC свідомо (ревʼю с24): половина часових багів проєкту —
       про зсув доби, а в UTC вони не відтворюються. Київ = UTC+2/+3, тож
       «YYYY-MM-DD» через new Date() тут з'їжджає на добу і тести це ловлять. */
    env: { TZ: "Europe/Kyiv" },
  },
});
