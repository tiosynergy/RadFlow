/* с85 (Н-27(и), ревʼю с84-B лінза C): заборона вбудовувати RadFlow у ЧУЖІ фрейми
   (clickjacking). До с85 не було ні `X-Frame-Options`, ні `frame-ancestors`.
   Чесна межа (ревʼю с85, лінза C): живу сесію в чужому фреймі вже не давала cookie
   Supabase — `@supabase/ssr` ставить їх `SameSite=Lax`, а такі cookie не їдуть у
   cross-site iframe і не записуються з нього; чужий фрейм із /platform чи /queue
   отримував /login. Тому заголовки — ДРУГА лінія, а не латка живої діри: вони не
   дають показати в чужому фреймі жодної сторінки (і форму входу теж) і не залежать
   від того, чи лишиться cookie Lax (власний домен із сусідніми same-site піддоменами,
   колись `SameSite=None`). Підміну кліку на ВЕРХНЬОМУ рівні (DoubleClickjacking —
   вікно-приманка перенаправляє opener на консоль між двома кліками) вони не
   закривають — це окремий пункт ToDo (Н-27(л)).
   Обидва заголовки свідомо: `Content-Security-Policy: frame-ancestors` — чинний
   стандарт, `X-Frame-Options` — для браузерів без CSP-рівня 2; де є обидва, сучасний
   браузер слухає CSP. `'self'`, а не `'none'`: у самому продукті iframe немає, але
   AGENTS.md описує перевірку вузьких екранів через `<iframe src="/queue">` ТОГО Ж
   походження у вкладці власника — `'none'` мовчки показав би там порожню рамку
   (`next dev` теж віддає ці заголовки; ревʼю с85, лінза C). Чужому походженню
   `'self'` не дозволяє нічого: походження — точний хост, а не *.vercel.app (той —
   у Public Suffix List).
   ⚠️ Переглянути `'self'` → `'none'` у проді, якщо (а) зʼявиться CSP скриптів (тоді
   HTML-інʼєкція без виконання скриптів могла б вставити iframe консолі з накладкою на
   ТОМУ Ж походженні) або (б) походження почне віддавати вміст користувачів інлайн
   (вкладення направлень тощо). Сьогодні жодного з двох немає (ревʼю с85, лінза C).
   Повну CSP (скрипти, стилі) цей заголовок НЕ вводить — це окремий пакет: інлайн-скрипти
   Next і стилі потребують nonce/хешів, і зламати сторінку тут дорожче, ніж виграти.
   Якщо колись CSP із nonce ставитиме middleware — `frame-ancestors` треба повторити там. */
const SECURITY_HEADERS = [
  { key: "Content-Security-Policy", value: "frame-ancestors 'self'" },
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  /* Заборона вгадувати тип вмісту: відповідь без Content-Type (майбутній
     `new Response(bytes)`) браузер не перетворить на HTML. Усі наші відповіді
     типізовані — JSON, CSV/XLSX як вкладення, fhir+json (замір с85). */
  { key: "X-Content-Type-Options", value: "nosniff" },
];

