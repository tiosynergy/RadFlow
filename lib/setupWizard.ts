/* ===== RadFlow — майстер налаштувань: знімок «збереженого» =====

   Майстер `/setup` вважає форму брудною, порівнюючи JSON поточних даних зі
   знімком останнього успішного збереження (`savedRef`). Знімок і стан форми
   мусять збігатись символ у символ — інакше «Вийти» питає про незбережені
   зміни там, де їх немає, і оператор або втрачає довіру до попередження, або
   починає його ігнорувати. Обидва наслідки однаково погані.

   ЛОВУШКА (легасі; знайдено ревʼю с43, полагоджено с44).
   Після першого «Зберегти» нові кабінети отримують db-id, і батько віддає їх
   назад у стан форми через ref `assignRoomIdsRef` (у формі це проп
   `assignRoomIds`) — канал проти багу с33 (див.
   коментар біля `useState(equip)` у StepRegister). Але `setEquip` — це
   ЗАПЛАНОВАНЕ оновлення стану: коли save() одразу після нього писав
   `savedRef.current = JSON.stringify(d)`, у знімок їхав `d` БЕЗ виданих id.
   React застосовував оновлення, ефект форми звітував новими даними — і
   `dirty` спалахував true на рівному місці, без жодної правки користувача.

   Тому видані id підмішує ОДНА функція, і кличуть її обидві сторони: форма
   (усередині setEquip) і знімок (`savedSnapshot` нижче, а через нього —
   `dirtyAfterSave`). Розійтись вони вже не можуть — у цьому весь сенс виносу.

   ⚠️ ДРУГИЙ БІК ТОГО САМОГО. Знімок будується з `d.equip`, тобто з того, що
   САМЕ ЗБЕРЕГЛИ, а не з поточного стану форми: поля під час збереження не
   блокуються, і правки, набрані ПОКИ воно тривало, мусять лишитись
   незбереженими. Тому save() після знімка НЕ гасить dirty голим `false`, а
   ПЕРЕРАХОВУЄ його — тим самим підмішуванням id, щоб ще не застосований
   setEquip не виглядав правкою (ревʼю с44). Виданий id — не правка
   користувача, а бухгалтерія, і на обох боках порівняння він однаковий. */

/** Пара «локальний id рядка форми → виданий базою room id». */
export type RoomIdAssignment = { localId: number | string; roomId: string };

/** Мінімум, потрібний від рядка обладнання: локальний id і (можливо) db-id. */
export type EquipWithRoomId = { id: number | string; roomId?: string };

/**
 * Підмішує видані базою room id у рядки обладнання.
 *
 * Рядок, у якого db-id УЖЕ є, не чіпаємо: перезапис означав би підміну
 * кабінету.
 *
 * ⚠️ Локальні id всередині ОДНІЄЇ сесії форми унікальні, але схеми дві:
 * рядки з сервера нумеруються лічильником `i + 1` (`app/setup/page.tsx`) і
 * ЗАВЖДИ мають roomId, а додані в браузері беруть `Date.now()`
 * (`addEq` у SetupWizard) і roomId не мають. Не «зводьте їх до єдиного
 * вигляду»: лічильник для нових рядків дав би id, що збігається з серверним,
 * і виданий db-id заштампувався б у чужу картку. Порівнюємо через `String()`
 * просто тому, що у формі число, а в базі рядок.
 *
 * Порожній `assigned` повертає ТОЙ САМИЙ масив (а не копію): по-перше, це
 * реальна гілка з боку знімка — коли нових кабінетів не було або канал у
 * форму обірвано, save() передає сюди `[]`; по-друге, збережена ідентичність
 * не дає зайвого рендера, якщо функцію колись покличуть із setEquip без
 * зовнішнього гарда.
 * Непорожній `assigned` дає НОВИЙ масив, а рядок-збіг — НОВИЙ обʼєкт: інакше
 * React не побачив би зміни стану, і видані id не доїхали б до ефекту форми.
 */
export function applyAssignedRoomIds<T extends EquipWithRoomId>(
  equip: T[],
  assigned: RoomIdAssignment[],
): T[] {
  if (!assigned.length) return equip;
  return equip.map((e) => {
    const hit = assigned.find((x) => String(x.localId) === String(e.id));
    return hit && !e.roomId ? { ...e, roomId: hit.roomId } : e;
  });
}

/** Будь-які дані форми майстра, у яких є список обладнання. */
export type EquipCarrier = { equip: EquipWithRoomId[] };

/**
 * Знімок «збереженого» для `savedRef`.
 *
 * `saved` — те, що save() САМЕ ЗАПИСАВ у базу (зняте на початку виклику), а
 * не поточний стан форми. `handed` — id, які реально поїхали у форму: якщо
 * канал обірвано, сюди передають `[]`, і тоді їх немає й у знімку (інакше
 * dirty залипне в true назавжди).
 */
export function savedSnapshot<D extends EquipCarrier>(saved: D, handed: RoomIdAssignment[]): string {
  return JSON.stringify({ ...saved, equip: applyAssignedRoomIds(saved.equip, handed) });
}

/**
 * Чи лишились у формі незбережені правки ПІСЛЯ успішного збереження.
 *
 * Голий `setDirty(false)` тут був дефектом: поля форми під час збереження не
 * блокуються (disabled лише кнопки), і набране за цей час оголошувалось
 * збереженим — кнопка «Зберегти» гасла, «Вийти» не питало, а текст лишався в
 * полі. Порівнюємо тим самим підмішуванням id, інакше ще не застосований
 * setEquip сам виглядав би правкою.
 *
 * `current === null` (форми ще немає) → не брудно: приписати незбережені
 * зміни порожнечі гірше, ніж промовчати.
 */
export function dirtyAfterSave<D extends EquipCarrier>(
  current: D | null,
  snapshot: string,
  handed: RoomIdAssignment[],
): boolean {
  return !!current && savedSnapshot(current, handed) !== snapshot;
}
