/* ===== RadFlow — довіра до годинника КЛІЄНТА на запис, виведений із «сьогодні» =====
   Г1-F (с54). Рішення власника: сервер НЕ ПРИЙМАЄ добу, виведену з розбіжного
   годинника; лікуємо причину, а не пояснюємо наслідок.

   ЩО ЦЕ ЗАКРИВАЄ, ДОСЛІВНО. `useFollowToday` переносить дату екрана за
   поправкою годинника, але під `busy` перенесення ВІДКЛАДАЄТЬСЯ. У форм із
   `busy: saving` (`RescheduleModal`, `WaitlistModal`) збереження — це і є
   `busy`: поправка, що прийшла за час запиту, відкладається, модалка на успіху
   закривається, хук розмонтовується — і відкладений ключ помирає разом із ним.
   Виміряно зондом на самому ядрі (с54): під `busy` `apply = null`, після
   розмонтування `applies = []`, а в БД їде дата ДО поправки — обидві форми
   збирають полезне навантаження ДО `await`.

   ЧОМУ ГАРД СТОЇТЬ НА СЕРВЕРІ, А НЕ В ФОРМІ. Форму на успіху закриває БАТЬКО
   (8 місць у 4 файлах, контракт «успіх → батько закриває» записаний у самій
   модалці), тож сказати щось із форми після відповіді нема кому. Сервер же
   тримає правду про час незалежно від того, що думає браузер.

   ⚠️ НАЗВАНА МЕЖА №1, і перша редакція цієї шапки її ПРИХОВУВАЛА (знахідка
   ревʼю, HIGH; тут стояло «сервер знає правду завжди — незалежно від того,
   коли поправка доїхала до браузера»). Це неправда, і ось точна межа. Прапорець
   `fromToday` рахує КЛІЄНТ проти СВОГО поточного «сьогодні» (`serverNow()` —
   уже виправленого). Тож гард ловить рівно те, заради чого писався: поправка
   приземлилась ПІД ЧАС запиту, а навантаження складене до неї — тоді заявка
   несе стару добу і старий момент, і сервер бачить розбіжність. Але якщо
   поправка приземлилась РАНІШЕ кліка, а поле лишилось старим (перенесення
   відкладене довгим `busy`), клієнт порахує `fromToday: false` — «людина обрала
   сама» — і гард промовчить. У двох формах цього пакета такий стан недосяжний
   (`busy` тут тримається рівно на час запиту, тож до кліка відкладене
   перенесення вже застосоване), крім вузької щілини між приземленням поправки і
   найближчим прогоном ефекту. Для форм із ДОВГИМ `busy` (набраний кейс) цей
   стан досяжний — там про нього говорить `dayStop` з Г1-A, а не цей гард.

   ⚠️ НАЗВАНА МЕЖА №2: пакет закриває шляхи Г1-F — перенос запису і лист
   очікування. `createBooking` / `createReferralBooking` / `scheduleFromWaitlist`
   заявки не возять і гарда НЕ мають; `BookingModal` заявку не будує. Це не
   пропуск, а межа узгодженого обсягу — і саме тому вона названа тут, а не
   лишена читачеві на здогад.

   ЧОМУ НЕ МІГРАЦІЯ (перевірено, а не припущено). Обидва шляхи запису — Server
   Actions; лист очікування пише в таблицю ПРЯМО, без RPC. А головне: БД не може
   знати, що дата була ВИВЕДЕНА з клієнтського «сьогодні», поки клієнт їй цього
   не скаже, — тобто «останній рубіж у тригері» тут неможливий за побудовою, а
   не «не встигли». Це названа межа пакета.

   ⚠️ ДВІ УМОВИ, А НЕ ОДНА — і друга не косметична. Порівнювати самі доби НЕ
   МОЖНА: правило `useFollowToday` СВІДОМО не реагує на справжню північ
   (записане рішення — оператор дописує вчорашній день). Гард «доби не збіглись»
   відмовляв би рівно опівночі на чесній роботі з чесним годинником. Розбіжність
   МОМЕНТІВ відрізняє «годинник бреше» від «північ настала між кліком і
   сервером»: у другому випадку різниця моментів — це час польоту запиту. */

import { CLOCK_WORST_ERROR_MS, serverNow } from "./serverClock";
import { wallDayKeyAt } from "./incidents";

/** Що клієнт СТВЕРДЖУЄ про свій годинник у мить складання запиту. */
export type ClockClaim = {
  /** Момент за годинником клієнта — уже виправлений `serverNow()`, мс епохи. */
  nowMs: number;
  /** Доба клініки, порахована ТИМ САМИМ годинником, «YYYY-MM-DD». */
  dayKey: string;
  /** Дата в запиті — ДЕФОЛТ, виведений із цього «сьогодні», а не вибір людини.
      Рахує це не форма власноруч, а спільний `derivedFromToday`
      (`lib/useFollowToday.ts`) — той самий предикат, яким правило вирішує, чи
      переносити значення. Дві копії розійшлися б мовчки. */
  fromToday: boolean;
};

/** Бюджет на ПОЛІТ запиту: скільки серверний момент має право бути пізнішим за
    клієнтський просто тому, що між ними лежить мережа і холодний старт Server
    Action. Взято з запасом — ціна помилки асиметрична: завузький бюджет
    відмовляє ЧЕСНОМУ збереженню в справжню північ, зазанадто широкий лише
    лишає непійманими зсуви, менші за нього. */
export const CLOCK_TRUST_NET_BUDGET_MS = 30_000;

/** Допуск на розбіжність моментів. Складові названі поіменно:
      • `CLOCK_WORST_ERROR_MS` (2125) — найгірша похибка ВЖЕ ЗАСТОСОВАНОГО
        зсуву, виведена в `serverClock.ts`;
      • `CLOCK_TRUST_NET_BUDGET_MS` — політ запиту.
    ⚠️ НАЗВАНА МЕЖА: зсув, менший за цей допуск, гард НЕ ловить. Він рухає добу
    лише тоді, коли клік стався в межах допуску від півночі, — і саме там
    відрізнити його від справжньої півночі неможливо в принципі, бо
    спостереження однакові. Це не «руки не дійшли», це межа методу. */
export const CLOCK_TRUST_TOL_MS = CLOCK_WORST_ERROR_MS + CLOCK_TRUST_NET_BUDGET_MS;

export type ClockTrustVerdict = "ok" | "skew" | "malformed";

/* ⚠️ `[\s\S]` НЕ приймається, і `$` тут без прапорця `m` СВІДОМО не досить:
   у JS `$` без `m` усе одно пропускає завершальний `\n`. Тому довжина
   перевіряється окремо — інакше «2026-09-02\n» був би валідним ключем. */
const DAY_KEY_RE = /^\d{4}-\d{2}-\d{2}$/;
const isDayKey = (v: string) => v.length === 10 && DAY_KEY_RE.test(v);

/** ЧИСТЕ ПРАВИЛО. `ok` — писати можна; `skew` — годинник клієнта розійшовся і
    саме через це дата інша; `malformed` — заявка є, але зіпсована.

    ⚠️ ВІДСУТНЯ заявка — це `ok`, і це СВІДОМИЙ fail-open із названою ціною.
    Вкладка, відкрита ДО деплою, шле старе навантаження; fail-closed поклав би
    реєстратуру в мить розгортання — на цілу зміну, бо вкладки там живуть
    годинами. Відсутність заявки лишає рівно ту поведінку, що була до пакета:
    гірше не стає нікому.

    ⚠️ ЩО САМЕ ДАЄ ГІЛКА `malformed`, БЕЗ ПЕРЕБІЛЬШЕНЬ (поправка за ревʼю).
    Перша редакція цього коментаря стверджувала «зіпсоване поле означає
    крафтовий запит, і там fail-closed» — тобто приписувала гілці захист від
    зловмисника. Це неправда: зловмиснику нема сенсу псувати заявку, коли
    достатньо не слати її зовсім (`ok`) або поставити `fromToday: false` (`ok`).
    Гілка ловить ІНШЕ і теж потрібне: заявку, зіпсовану СВОЇМ кодом —
    перейменованим полем, серіалізацією `Date` у рядок, `undefined` замість
    числа. Такий вхід НЕ мовчить, а стає гучною відмовою; тихо пропустити його
    означало б вимкнути гард правкою, яку ніхто не помітить.

    ⚠️ ПОРЯДОК УМОВ Є ЧАСТИНОЮ ПРАВИЛА. `malformed` — перший: якщо структура
    зіпсована, вірити прапорцю `fromToday` теж не можна. */
export function clockClaimVerdict(
  claim: ClockClaim | null | undefined,
  server: { nowMs: number; dayKey: string },
  tolMs: number = CLOCK_TRUST_TOL_MS,
): ClockTrustVerdict {
  if (claim === null || claim === undefined) return "ok";
  if (
    typeof claim.nowMs !== "number" || !Number.isFinite(claim.nowMs) ||
    typeof claim.dayKey !== "string" || !isDayKey(claim.dayKey) ||
    typeof claim.fromToday !== "boolean"
  ) return "malformed";
  // Дату обрала ЛЮДИНА — її вибір не залежить від того, що думає годинник.
  if (!claim.fromToday) return "ok";
  // Доби збіглись: зсув (якщо він є) добу не перетинає, виведена дата вірна.
  if (claim.dayKey === server.dayKey) return "ok";
  // Доби різні, але моменти сходяться → між кліком і сервером була ПІВНІЧ.
  if (Math.abs(server.nowMs - claim.nowMs) <= tolMs) return "ok";
  return "skew";
}

/** СЕРВЕРНА сторона порівняння: момент і доба клініки, ОДНИМ інстантом.

    ⚠️ Момент береться раз — так само, як у `clockClaimOf`. Два виклики
    «зараз» на два поля дали б суперечливу пару рівно опівночі, тобто саме
    там, де гард працює.

    ⚠️ ЧИЙ ЦЕ ГОДИННИК. `serverNow()` на сервері дорівнює `Date.now()` процесу
    (зсув міряє лише браузер), тобто це годинник Node на Vercel — той самий, за
    яким уже судять сусідні `isPastSlot` і `clinicTodayKey` у цих же екшенах.
    Свідомо НЕ беремо `public.server_now()`: у гарді була б ОДНА величина з
    бази і ДРУГА з Node, а порівнювати їх між собою — це вводити в функцію
    другий годинник заради видимості канону. Розбіжність Node ↔ Postgres не
    вимірювалась — названа межа, і вона спільна з обома сусідами. */
export function serverClockNow(clinicTz?: string | null): { nowMs: number; dayKey: string } {
  const nowMs = serverNow();
  return { nowMs, dayKey: wallDayKeyAt(nowMs, clinicTz || undefined) };
}

