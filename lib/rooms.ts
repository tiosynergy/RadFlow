/* ===== RadFlow — вимкнені кабінети (0123) =====
   rooms.active: false = кабінет вимкнено. Правило власника (2026-07-27):
   вимкнений кабінет БІЛЬШЕ НЕ ПРИЙМАЄ записів (ні нових, ні переносів у нього,
   ні вейтліст-броні), але наявні записи лишаються робочими — їх ведуть,
   викликають, завершують і рухають по часу всередині того ж кабінету.

   Звідси два різні питання, які легко переплутати:
     • «чи можна СЮДИ записати» → isRoomBookable (форми запису, перенос, вейтліст);
     • «чи показувати кабінет» → показуємо ЗАВЖДИ (дошки, налаштування, історія,
       аналітика). Сховати вимкнений кабінет на дошці означало б загубити
       пацієнтів, які в ньому лишились: рядки стали б «без кабінету».

   active === undefined трактуємо як активний: старі селекти, що не тягнуть
   колонку, деградують безпечно — останній рубіж усе одно тригер БД
   check_room_active (0123), як і з services.room_id у 0121. */

export type RoomActivity = { active?: boolean | null };

/** Чи можна записувати в цей кабінет (0123). undefined → так (див. коментар вище). */
export function isRoomBookable(r: RoomActivity): boolean {
  return r.active !== false;
}

/** Кабінети, доступні для запису. */
export function bookableRooms<T extends RoomActivity>(rooms: T[] | null | undefined): T[] {
  return (rooms || []).filter(isRoomBookable);
}

/** Мітка для дошок і списків, де вимкнений кабінет ЛИШАЄТЬСЯ видимим. */
export const ROOM_OFF_LABEL = "вимкнено";
