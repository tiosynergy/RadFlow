/* ===== RadFlow — вимкнені кабінети =====

   `rooms.active = false` означає **кабінет виведено з експлуатації**, а НЕ «тимчасово
   не працює». Тимчасова зупинка (апарат зламався, профілактика, лікар у відпустці) —
   це ОКРЕМИЙ механізм: «Поломка / ТО» та «Аварійна зупинка» (інциденти,
   `check_not_during_incident`, червона підсвітка кабінету в сайдбарі). Не плутати.

   Звідси ТРИ різні питання, які легко злити в одне:

     • «чи можна СЮДИ записати»  → isRoomBookable / bookableRooms
       (форми запису, перенос, вейтліст). Останній рубіж — тригер БД
       `check_room_active` (0123): він не дасть ні створити, ні перенести, ні
       забронювати з вейтліста, але ДОЗВОЛЯЄ вести й закривати вже наявні записи —
       інакше день у вимкненому кабінеті став би невідпрацьовуваним.

     • «чи показувати кабінет у робочих списках» → isRoomVisible / visibleRooms.

     • «як назвати кабінет у рядку запису» → показуємо ЗАВЖДИ за room_id, з міткою.
       Фільтр стосується СПИСКІВ КАБІНЕТІВ, а не записів: історія й пошук пацієнта
       не змінюються ніколи. Тому в компоненти йде ПОВНИЙ список кабінетів (для
       резолву імені за id) плюс окремо множина залишків — фільтруються лише списки.

   ⚠️ УВАГА, ПРАВИЛО ЗМІНИЛОСЬ (2026-07-28). Раніше тут було записано протилежне:
   «показуємо ЗАВЖДИ (дошки, налаштування, історія, аналітика)». Той компроміс існував
   лише тому, що `active` тягнув обидва сенси одразу, і сховати кабінет означало б
   загубити пацієнтів, які в ньому лишились. Тепер ризик закрито інакше — «сплиттям»
   (нижче), тож вимкнений кабінет ХОВАЄМО з робочих екранів. Дизайн і повний перелік
   місць — у проєкті claude.ai «RadFlow», документ `claude/room-off-visibility-design.md`.

   СПЛИТТЯ («кабінет-залишок»). Вимкнений кабінет повертається у списки, поки в ньому
   лишається хоч один ЖИВИЙ рядок (запис від сьогодні й далі або активний вейтліст), —
   з підписом «вимкнено · N записів». І зникає САМ, коли останній закрито чи перенесено.
   Тому вимкнути кабінет можна будь-коли, нічого не блокуючи, і при цьому загубити
   пацієнта фізично неможливо. Хто рахує залишки — `lib/roomsResidual.ts` (сервер).

   `active === undefined` трактуємо як активний: старі селекти, що не тягнуть колонку,
   деградують безпечно — останній рубіж усе одно тригер БД. */

export type RoomActivity = { active?: boolean | null };
export type RoomWithId = RoomActivity & { id: string };

/** Чи можна записувати в цей кабінет (0123). undefined → так (див. коментар вище). */
export function isRoomBookable(r: RoomActivity): boolean {
  return r.active !== false;
}

/** Кабінети, доступні для запису. */
export function bookableRooms<T extends RoomActivity>(rooms: T[] | null | undefined): T[] {
  return (rooms || []).filter(isRoomBookable);
}

/** Мітка вимкненого кабінету. */
export const ROOM_OFF_LABEL = "вимкнено";

/**
 * Чи показувати кабінет у РОБОЧОМУ списку (сайдбар, фільтри, вибір кабінету).
 * Вимкнений видно лише поки він «залишок» — тобто в ньому ще є живі рядки.
 *
 * `residual` не передали (undefined) → вважаємо, що залишків немає. Це свідомий
 * fail-closed для ВИДИМОСТІ: краще сховати порожній кабінет там, куди виклик ще
 * не прокинули, ніж показати всі вимкнені й повернути стару поведінку мовчки.
 * Ризику загубити пацієнта тут немає — рядки запису резолвляться за room_id із
 * повного списку, а не через цей фільтр.
 */
export function isRoomVisible(r: RoomWithId, residual?: ReadonlySet<string> | null): boolean {
  if (r.active !== false) return true;
  return !!residual && residual.has(r.id);
}

/** Кабінети для робочих списків: активні + вимкнені із залишками. */
export function visibleRooms<T extends RoomWithId>(
  rooms: T[] | null | undefined,
  residual?: ReadonlySet<string> | null,
): T[] {
  return (rooms || []).filter((r) => isRoomVisible(r, residual));
}

/** SSR віддає залишки масивом (JSON-серіалізовно) — клієнт робить із нього Set. */
export function residualSet(ids: string[] | null | undefined): ReadonlySet<string> {
  return new Set(ids || []);
}

/* Українська множина для «запис»: 1 запис, 2–4 записи, 5–20 записів,
   далі — за останньою цифрою (21 запис, 22 записи, 25 записів). */
export function pluralZapys(n: number): string {
  const abs = Math.abs(Math.trunc(n));
  const mod100 = abs % 100;
  const mod10 = abs % 10;
  if (mod100 >= 11 && mod100 <= 14) return "записів";
  if (mod10 === 1) return "запис";
  if (mod10 >= 2 && mod10 <= 4) return "записи";
  return "записів";
}

/**
 * Підпис вимкненого кабінету у списку.
 * Без залишків — просто «вимкнено»; із залишками — «вимкнено · 3 записи»,
 * щоб персонал одразу бачив, ЧОМУ кабінет ще тут і скільки лишилось розібрати.
 */
export function roomOffLabel(count?: number | null): string {
  if (!count || count <= 0) return ROOM_OFF_LABEL;
  return `${ROOM_OFF_LABEL} · ${count} ${pluralZapys(count)}`;
}
