/* ===== RadFlow — графік кабінету в модалках ОНОВЛЮЄТЬСЯ, поки вікно відкрите =====
   Замір (с63): три модалки — `BookingModal`, `RescheduleModal`, `StudyEditModal` —
   читали `rooms.schedule` і особливий графік дня РІВНО ОДИН РАЗ, у `useEffect`
   зі статичними залежностями `[roomId, dateStr, clinicId]`. Ні підписки, ні
   тика. Тобто адмін закриває день або переносить перерву — а людина з уже
   відкритою модалкою НЕОБМЕЖЕНО ДОВГО бачить і обирає слоти СТАРОГО графіка.
   Сервер такий запис відхилить (`scheduleGate` в `app/queue/actions.ts`), але
   користувач дізнається про це вже після «Зберегти», без жодного банера до.

   ⚠️ Ключ був поруч увесь час: ЗАЙНЯТІСТЬ у тих самих модалках давно береться
   спільним хуком `useRoomBusy` (lib/slotBusy.ts) — з realtime і тиком. Тобто
   половина сітки оновлювалась, а половина ні, і жодна з трьох модалок про це
   не говорила. Цей хук — те саме правило для ДРУГОЇ половини.

   ЧОМУ ОКРЕМИЙ ФАЙЛ, а не функція в `lib/roomSchedule.ts`. Той файл імпортує
   СЕРВЕРНИЙ `app/queue/actions.ts` (перепис місць виклику — у
   `tests/roomScheduleRead.test.ts`), а тут `"use client"` і хуки. Директива в
   спільному файлі зламала б серверний імпорт.

   ⚠️ ЦІНА, НАЗВАНА ВГОЛОС. Доти графік читався РІВНО РАЗ — на відкритті вікна,
   — тож транзієнтний збій мережі при вже відкритій модалці не міг зробити
   нічого. Тепер може: лоадери всіх трьох на помилці обнуляють прочитане і
   піднімають `schedErr`, тобто блимання зв'язку під час вибору слота ЗГОРНЕ
   сітку і покаже банер «графік невідомий» — до наступної події або тика (30 с).
   Це свідомо: показувати сітку СТАРОГО графіка як факт — рівно той fail-open,
   проти якого написані U-13 і U-16, і `useRoomBusy` на своїй половині сітки
   поводиться так само з першого дня.

   ЧОМУ ХУК НЕ ЧИТАЄ САМ, а лише кличе чужий лоадер. Читання `rooms.schedule`
   зобовʼязане стояти ВПРИТУЛ до гейта `if (!sched.known) throw` — це пінить
   сканер U-13 (`tests/roomScheduleRead.test.ts`, тест «незнання ЗУПИНЯЄ потік у
   КОЖНОМУ місці виклику»), і кожна з трьох модалок перелічена в його CENSUS
   поіменно. Забравши читання в хук, я зняв би з-під нагляду три з семи місць
   заради косметики. Тут виноситься лише те, що справді однакове і що легко
   зіпсувати мовчки: імʼя каналу, ФІЛЬТРИ підписок і період тика. */

"use client";

import { useRealtimeRefetch } from "@/lib/useRealtimeRefetch";

/** Період «повільного» тика при ЖИВОМУ сокеті.
 *
 *  ⚠️ Це не страховка «на випадок обриву» (для обриву в хуку є власний backoff),
 *  а ЄДИНИЙ шлях доставки для направника — і так записано в самій міграції
 *  0183 (RF-03): «Для направника затримку покриває наявний pollWhenSubscribedMs
 *  30_000». Політику `sched_referrer_read` знято, тож подій по
 *  `schedule_overrides` направник не отримує ВЗАГАЛІ, скільки б сокет не жив.
 *  Те саме число, що в `useRoomBusy` і в `ReferralPortal`, — свідомо: дві
 *  половини однієї сітки, що оновлюються з різним періодом, дають кадри, у яких
 *  зайнятість уже нова, а межі дня ще старі. */
export const SCHED_POLL_MS = 30_000;

/**
 * Realtime + рідкий тик для ГРАФІКА кабінету на конкретну дату.
 *
 * Викликач лишає собі власний лоадер (читання + гейт U-13) і передає його сюди
 * як `onChange`. Хук не має жодного стану: він лише вирішує, КОЛИ перечитати.
 *
 * ⚠️ `onChange` НЕ повинен піднімати прапорець «завантаження»: це фонове
 * перечитування при відкритому вікні, і блимання сітки в «…» на кожен тик
 * виглядало б збоєм. Взірець — `BookingModal`: `setSchedLoading(true)` стоїть у
 * власному ефекті ПОРУЧ із викликом, а не всередині `loadSched`.
 *
 * ⚠️ `onChange` зобовʼязаний бути захищений лічильником поколінь (`reqRef`).
 * Прапорця `cancel` із замикання ефекту тут НЕ досить: подія прилітає ПОЗА тим
 * ефектом, тож його `cancel` до цього виклику не має стосунку взагалі, і
 * відповідь по старому кабінету/даті перетерла б нову.
 */
export function useScheduleRefetch(opts: {
  /* ⚠️ Обовʼязковий КЛЮЧ при можливо порожньому значенні — той самий прийом, що
     з `clinicId` у `useRoomBusy` (U-65): обовʼязковість ТИПУ змушує tsc
     перелічити місця виклику. Порожнє значення не «знімає фільтр», а вимикає
     підписку ЦІЛКОМ: краще без realtime, ніж без фільтра (U-61 — на DELETE
     політика не обчислюється, тож без фільтра підписка ловить факт кожного
     видалення в УСІЙ базі). */
  clinicId: string | null | undefined;
  /** Дата, на яку дивиться сітка (YYYY-MM-DD). Без неї перечитувати нічого. */
  dateStr: string | null | undefined;
  /* ⚠️ Лише частина ІМЕНІ каналу, а не фільтр. Кабінет у модалці МІНЯЄТЬСЯ
     (`RescheduleModal`), а `rooms` у підписці фільтрується по клініці — див.
     нижче, чому саме так. */
  roomId: string | null | undefined;
  /* ⚠️ ОБОВʼЯЗКОВИЙ і РІЗНИЙ у кожного викликача. `RescheduleModal` монтує
     всередині себе `BookingModal` (шлях «переоформлення в інший кабінет»), тож
     два виклики цього хука з тим самим кабінетом і датою живуть ОДНОЧАСНО. Без
     розрізнення вони просили б у Supabase канал з однаковою назвою. */
  scope: string;
  /** Що перечитати. Див. дві ⚠️ вище — прапорець і лічильник поколінь. */
  onChange: () => void;
  enabled?: boolean;
}) {
  /* ⚠️ `onChange` перейменовано в `reload` НАВМИСНО, і це не стиль. Сканер
     поверхні підписок (`tests/realtimeSubscriptionSurface.test.ts`) відрізняє
     підписку від будь-якого іншого обʼєкта з ключем `table` за наявністю
     `onChange:` або `schema:` — саме з ДВОКРАПКОЮ. Записані скорочено
     (`{ table, filter, onChange }`), обидві підписки нижче були б для нього
     НЕВИДИМІ: зняття фільтра пройшло б повз U-61 при зеленому тесті. Знайдено
     при написанні стенда, а не ревʼю. */
  const { clinicId, dateStr, roomId, scope, onChange: reload, enabled = true } = opts;

  useRealtimeRefetch({
    /* Кабінет — у ІМЕНІ каналу: його зміна має перестворити канал, інакше
       `skipInitial` нижче лишив би нову дату/кабінет без жодного запиту до
       першої чужої події. (Сам запит робить власний ефект викликача — але
       канал усе одно мусить відповідати поточному scope.) */
    channelName: enabled && clinicId && dateStr
      ? "sched-" + scope + "-" + clinicId + "-" + (roomId || "none") + "-" + dateStr
      : null,
    subscriptions: [
      /* ⚠️ Спільний `debounceKey`: обидві таблиці ведуть в ОДИН лоадер, і без
         ключа сплеск (адмін зберіг графік — правка `rooms` плюс `schedule_overrides`)
         кликав би його двічі.

         ⚠️ `clinic_id=eq.` на ОБОХ (U-61). Клініку не міняє ні кабінет, ні
         особливий день, тож фільтр не ріже нічого потрібного.

         ⚠️ `rooms` — саме по клініці, а НЕ `id=eq.roomId`. У модалці переносу
         кабінет перемикають чипами, і підписка по id мусила б перепідписуватись
         на кожен клік; по клініці канал живе, поки живе вікно. Ціна названа:
         правка графіка СУСІДНЬОГО кабінету теж смикне лоадер — це один
         `maybeSingle` по своєму кабінету, дешевше за перепідписку.

         ⚠️ `schedule_overrides` лишається в переліку, хоч направнику подій по
         ній не доставляють (0183 зняла `sched_referrer_read`): усі три модалки
         відкриває і ПЕРСОНАЛ, у якого жива `sched_staff_read` — для нього це
         миттєве перемальовування. Знявши підписку, я зламав би персоналу
         миттєвість заради направника, у якого її й так немає (те саме рішення й
         та сама причина, що записані в `ReferralPortal`).

         ⚠️ `skipInitial` на ОБОХ: первинне завантаження робить власний ефект
         викликача — інакше кожне відкриття модалки читало б графік ДВІЧІ
         (урок U-62/Д5, `WaitlistBoard`). Наслідок, названий вголос: якщо
         викликач прибере свій ефект, вікно відкриється БЕЗ графіка і чекатиме
         першої події — тому ефект є в усіх трьох і пінитись мусить у них. */
      { table: "schedule_overrides", filter: "clinic_id=eq." + clinicId, onChange: reload, debounceKey: "sched", skipInitial: true },
      { table: "rooms", filter: "clinic_id=eq." + clinicId, onChange: reload, debounceKey: "sched", skipInitial: true },
    ],
    pollWhenSubscribedMs: SCHED_POLL_MS,
  });
}
