/* ===== RadFlow — довіра до даних про доступність кабінету =====
   Одне правило для екранів, які СТВЕРДЖУЮТЬ «слот вільний» і дають зберегти
   запис: BookingModal (персонал) і ReferralPortal (направник).

   Аудит с46, U-5. Обидва екрани вже вміли ховати СІТКУ при збої («порожній
   день виглядав би як усе вільно»), але блок підтвердження «✓ Слот вільний»
   стояв ПОЗА цією умовою, а `valid` про збій не знав узагалі. Тож при обраному
   часі екран показував червоний банер «показати вільний час не можемо» і зелене
   «✓ Слот вільний» ОДНОЧАСНО, а «Зберегти» лишалась активною. Через prefill
   (кандидат на вікно, що звільнилося) досяжний шлях, де ПЕРША загрузка впала і
   spans справді порожні — тоді «вільний» стверджувалось на нульових даних, а не
   на застарілих.

   Правило: стверджувати про вільний час можна лише тоді, коли дані, на яких
   стоїть це твердження, завантажились і не впали. Порожній масив spans — це
   «не знаємо», а не «вільно». Цілісність тримає БД (check_no_overlap,
   check_not_during_incident), але помилка в лоб ПІСЛЯ «Зберегти» — не те саме,
   що чесний блок заздалегідь.

   Чиста функція, а не хук, свідомо: компонентних тестів у проєкті немає
   (`vitest.config.ts` — environment: "node"), тож правило, ціна помилки якого
   висока, живе в lib/ і покривається тестом. */

export type SlotDataState = {
  /** Зайнятість кабінету (RPC room_busy_slots) не завантажилась. */
  busyFailed: boolean;
  /** Графік кабінету / особливий графік дня не завантажились. */
  schedFailed: boolean;
  /** Запит ще в польоті: spans поки що [] — це «не знаємо», а не «вільно». */
  loading: boolean;
};

/** Чого бракує, щоб стверджувати про вільний час, або null — даним можна вірити.
    Рядок іде у футер модалки поруч з іншими незаповненими полями: «Зберегти»
    гасне разом із ним, і причина видима, а не «кнопка чомусь не працює». */
export function slotDataMissLabel(s: SlotDataState): string | null {
  /* Збій — ПЕРЕД завантаженням: якщо попередній запит упав, а новий уже в
     польоті, оператору важливіша причина, а не спінер. */
  if (s.busyFailed && s.schedFailed) return "Зайнятість і графік кабінету";
  if (s.busyFailed) return "Зайнятість кабінету";
  if (s.schedFailed) return "Графік кабінету";
  if (s.loading) return "Перевіряємо зайнятість…";
  return null;
}

/** Чи можна СТВЕРДЖУВАТИ, що слот вільний (показувати «✓ Слот вільний»). */
export function slotDataTrusted(s: SlotDataState): boolean {
  return slotDataMissLabel(s) === null;
}

/** Коли завантаження одне на все (один `catch` на кілька запитів, як у порталі
    направника) — обидві причини збігаються. Іменований конструктор замість
    ручного дублювання прапорця: переплутати місцями два `boolean` в літералі
    компілятор не заважає, а тут плутати нічого (ревʼю с46 р2, F11). */
export function slotDataFromSingleSource(failed: boolean, loading: boolean): SlotDataState {
  return { busyFailed: failed, schedFailed: failed, loading };
}

/** Повний рядок для футера екрана, де немає чипів «чого бракує»
    (RescheduleModal). Розділяє СБІЙ і ПОЛІТ: «Не завантажилось: перевіряємо
    зайнятість…» — безглуздя, і бачив би його оператор при КОЖНОМУ відкритті
    модалки, бо loading стартує з true (ревʼю с46 р3, F3). */
export function slotDataFooterText(s: SlotDataState): string | null {
  const label = slotDataMissLabel(s);
  if (label === null) return null;
  if (s.busyFailed || s.schedFailed) return "Не завантажилось: " + label.toLowerCase();
  return "⏳ " + label;
}

