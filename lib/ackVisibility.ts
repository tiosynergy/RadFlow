/**
 * U-59 — рішення «чи можна гасити позначки прямо зараз», винесене з
 * `useAckWhenVisible` (`lib/useUnreadChanges.tsx`).
 *
 * ЧОМУ ОКРЕМИЙ МОДУЛЬ — та сама причина, що й у `lib/realtimeRefetchPolicy.ts`
 * (пакет 33): DOM-тестів у проєкті немає НАВМИСНО (шапка `vitest.config.ts` —
 * тести це чисті функції з `lib/*`), тож поведінку React-хука довести нічим.
 * Рішення живе тут і пінується ПОВЕДІНКОЮ; те, що хук його КЛИЧЕ, тримає
 * лексичний пін у `tests/ackVisibility.test.ts`.
 *
 * ⚠️ МЕЖА, названа чесно: модуль стереже ПРАВИЛО, а не його застосування.
 *    Довести застосування поведінкою можна лише DOM-тестом, а це зміна
 *    прийнятого підходу — розвилка власника (Р4), не моє рішення.
 */
import type { UnreadStatus } from "@/lib/unreadChanges";

/**
 * Чи показано документ людині.
 *
 * ⚠️ Fail-CLOSED, і напрям обраний свідомо: усе, що не рівно `"visible"`,
 *    вважаємо «не показано». Ціна помилки в цей бік — позначка повисить
 *    непрочитаною зайву мить. Ціна помилки в інший бік — вона згасне, так
 *    нікому й не показавшись, а це рівно той дефект (U-59), заради якого
 *    модуль заведено.
 */
export function isDocumentShown(visibilityState: string | undefined): boolean {
  return visibilityState === "visible";
}

export type AckGateInput = {
  /** scope є — блокові взагалі є що підтверджувати */
  hasScope: boolean;
  /** компонент каже «блок розгорнуто І дані завантажились» */
  surfaceVisible: boolean;
  /** документ показано людині — результат `isDocumentShown` */
  documentVisible: boolean;
  status: UnreadStatus;
};

/**
 * - `collapse` — блок згорнувся або зник scope: ЗАМОРОЗКУ СКИНУТИ, наступне
 *   розкриття зафіксує новий знімок.
 * - `hold`     — вкладка у фоні: нічого не гасимо, але заморозку ЗБЕРІГАЄМО.
 * - `wait`     — індекс ще не `ready`: нічого не гасимо, заморозку зберігаємо.
 * - `ack`      — можна гасити заморожені id.
 */
export type AckGateDecision = "collapse" | "hold" | "wait" | "ack";

/**
 * ⚠️ ПОРЯДОК ГІЛОК І Є СЕМАНТИКОЮ — читати як три окремі властивості, бо
 *    кожна ламається СВОЄЮ мутацією, і жодна не випливає з решти.
 *
 * 1. `collapse` СТОЇТЬ ПЕРШИМ. Згорнутий блок скидає заморозку незалежно від
 *    того, показано документ чи ні. Це поведінка, яка була до U-59, і вона
 *    мусить пережити правку: якби `hold` стояв вище, згортання блока під
 *    фоновою вкладкою залишало б живою заморозку, якої вже нема чому належати.
 *
 * 2. `hold` — НЕ `collapse`, і це рішення власника (с58). Скинути заморозку на
 *    догляді вкладки означало б, що повернення робить НОВИЙ знімок і гасить
 *    усе, що прилетіло, поки людина дивилась в інше вікно, — рівно та тиша,
 *    через яку U-59 і заведено. Тому по поверненні гасяться ТІЛЬКИ ті id, що
 *    були в пулі до догляду; решта чекає наступного справжнього розкриття.
 *
 * 3. `hold` — і НЕ `ack`. Це власне лікування U-59: «відрендерено в DOM» не
 *    дорівнює «показано людині».
 *
 * ⚠️ ПЕРША РЕДАКЦІЯ ЦЬОГО МОДУЛЯ БУЛА НЕПОВНОЮ, і це знайшли ОБА раунди
 *    ревʼю (с58). `hold` берегла заморозку, але НЕ ключ у ній: поверхня з
 *    `refreezeKey` (постійно розгорнута — простої на дошці, лист у порталі)
 *    перечитувалась у фоні, ключ мінявся, і повернення на вкладку робило
 *    ПЕРЕЗАМОРОЗКУ по поточному пулу — тобто гасило рівно те, що прилетіло
 *    без людини, за 100–300 мс, поки вона ще не перевела погляд. Тобто для
 *    трьох найактивніших поверхонь U-59 не закривався взагалі.
 *    Лікує `nextFreeze` нижче: у фоні ключ НЕСЕТЬСЯ ДАЛІ, id — ні.
 *
 * ⚠️ МЕЖА: половина U-59 про «поверхню перекрито модалкою» цим модулем НЕ
 *    закрита. ⚠️ І ціна її закриття НЕ «окремий пакет», як стверджувала
 *    перша редакція цього коментаря: ознака вже порахована
 *    (`anyModalOpen`, `QueueBoard.tsx`), а її ПОВНОТУ вже стереже тест із
 *    с52 (`tests/followToday.test.ts` — рахує гейти оверлеїв із джерела).
 *    Лишається четвертий вхід `overlayShown` з наслідком `hold` плюс проп у
 *    рядок — порядок десяти рядків. Названо в хендофі саме так.
 */
export function ackGate(i: AckGateInput): AckGateDecision {
  if (!i.hasScope || !i.surfaceVisible) return "collapse";
  if (!i.documentVisible) return "hold";
  if (i.status !== "ready") return "wait";
  return "ack";
}

/** Заморожений знімок розкриття — те, що хук тримає в `frozenRef`. */
export type AckFreeze = {
  key: string;
  refreeze: string;
  uid: string | null;
  ids: string[];
};

/**
 * Наступний стан заморозки за ОДИН прогін ефекту. Уся арифметика заморозки
 * живе тут, у хука лишається одне присвоєння — саме тому «скидів заморозки
 * рівно один» стало властивістю, яку видно з коду, а не обіцянкою.
 *
 * `null` на виході — заморозку скинуто.
 *
 * ⚠️ ГІЛКА `hold` І Є ЛІКУВАННЯМ, знайденим ревʼю: ключ перезаморозки
 *    НЕСЕТЬСЯ ДАЛІ, а id — НІ. Без цього рядка поверхня з `refreezeKey`,
 *    що перечиталась у фоні, поверталась із розбіжним ключем і на першому ж
 *    прогоні під видимою вкладкою робила перезаморозку — тобто гасила саме
 *    те, чого людина не бачила. З ним ключ уже збігається, перезаморозки
 *    немає, і гасяться лише «доотходні» id.
 *
 * ⚠️ `wait` НЕ несе ключ: там документ ПОКАЗАНО, просто індекс ще не готовий.
 *    Перенести туди перенесення ключа означало б визнати показаним те, що
 *    людині не показували, — той самий дефект з іншого боку.
 */
export function nextFreeze(
  gate: AckGateDecision,
  prev: AckFreeze | null,
  now: { key: string; refreeze: string; uid: string | null },
  freshIds: () => string[],
): AckFreeze | null {
  if (gate === "collapse") return null;
  if (gate === "hold") {
    if (prev === null) return null;
    return prev.refreeze === now.refreeze ? prev : { ...prev, refreeze: now.refreeze };
  }
  if (gate === "wait") return prev;
  if (prev === null || prev.key !== now.key || prev.refreeze !== now.refreeze || prev.uid !== now.uid) {
    return { ...now, ids: freshIds() };
  }
  return prev;
}
