/* ===== RadFlow — повернення адміна з порталу направлень у свій центр =====
   Портал направлень (/referral) підміняє весь чром: замість адмінського
   сайдбару рендериться ReferrerSidebar, у якому немає жодного посилання
   назовні, а єдина кнопка — повний signOut. Адмін, який зайшов подивитись
   портал, опинявся в глухому куті й виходив із системи, щоб повернутись.

   Звідки прийшли, передаємо в ?from=. Значення — з АДРЕСНОГО РЯДКА, тобто
   недовірене: підставивши ?from=//evil.example або ?from=https://evil.example,
   зловмисник зробив би з нашої кнопки «Повернутися в центр» відкритий
   редирект під нашим доменом. Тому не «санітизуємо» рядок, а звіряємо зі
   списком відомих адмінських маршрутів: усе, чого в ньому немає, мовчки
   стає ADMIN_HOME. */

export const ADMIN_HOME = "/queue";

/* Сторінки, з яких адмін реально може відкрити портал (пункт у Sidebar видно
   на всіх них). Тримаємо як явний список, а не регулярку «починається з /»:
   регулярка пропускає і /login, і /referral, і будь-який майбутній маршрут. */
const ADMIN_ROUTES = new Set<string>([
  "/queue",
  "/call-list",
  "/waitlist",
  "/services",
  "/staff",
  "/referrers",
  "/setup",
  "/ceo",
  "/ceo-admin",
  "/radiologist",
]);

/** Безпечний шлях для кнопки «Повернутися»: лише відомий адмінський маршрут. */
export function safeBackHref(from: unknown): string {
  if (typeof from !== "string" || !from) return ADMIN_HOME;
  // Query і hash відрізаємо: /queue?tab=x — той самий маршрут, але тягнути
  // чужі параметри назад не потрібно, а '#' у білому списку не буде ніколи.
  const path = from.split("?")[0].split("#")[0];
  return ADMIN_ROUTES.has(path) ? path : ADMIN_HOME;
}
