/** Скільки живе посилання-запрошення. Рішення власника (с59): сім днів. */
export const INVITE_TTL_DAYS = 7;
export const INVITE_TTL_MS = INVITE_TTL_DAYS * 24 * 60 * 60 * 1000;

export type InviteState = "valid" | "expired" | "unstamped";

/**
 * Чи живе ще запрошення, видане в момент `issuedAt`.
 * @param issuedAt значення `profiles.invite_issued_at` (ISO або null)
 * @param now      «зараз» — параметром, щоб тест не залежав від годинника
 */
export function inviteState(issuedAt: string | null | undefined, now: Date = new Date()): InviteState {
  /* ⚠️ БЕЗ ШТАМПА — НЕ «дійсне». Штамп ставить тригер, тож його відсутність
     означає або рядок, що обійшов тригер, або тригер знято. Обидва випадки —
     привід відмовити, а не пропустити: fail-CLOSED. Саме тому це окремий
     стан, а не `true`/`false`: роут мусить мати змогу відрізнити «протухло»
     від «щось не так із самим механізмом». */
  if (!issuedAt) return "unstamped";
  const t = Date.parse(issuedAt);
  if (!Number.isFinite(t)) return "unstamped";
  return now.getTime() - t > INVITE_TTL_MS ? "expired" : "valid";
}
