/* ===== Межа пароля, яку насправді тримає сервер входу (с85, Н-27(з)) =====

   GoTrue хешує паролі bcrypt-ом, а bcrypt бачить лише 72 БАЙТИ UTF-8. Довший
   пароль GoTrue відхиляє ще до хешування: `checkPasswordStrength` у
   supabase/auth (`internal/api/password.go`, константа `MaxPasswordLength`,
   звірено з кодом у с85) робить `len(password) > 72` — Go рахує БАЙТИ — і
   повертає 400 `validation_failed` «Password cannot be longer than 72
   characters» (текст каже «characters», а рахує байти) на реєстрації, PUT /user
   і admin-створенні/оновленні. Схема ж `zPassword` пропускає 200 СИМВОЛІВ.
   Кирилиця — 2 байти на літеру, тож межа — ≈36 кириличних символів, і «довгу
   парольну фразу українською» вона ріже вже на середині.

   Що це давало до с85. Форми, які ставлять пароль через сервер, доходили до
   GoTrue і отримували відмову вже ПІСЛЯ своїх записів: `/api/account/set-password`
   гасив одноразовий токен, ловив відмову і відкочував клейм, а людина бачила
   загальне «не вдалося — спробуйте ще раз», не дізнаючись чому; адмін у
   «Задати пароль» — те саме; реєстрація показувала англійський текст GoTrue.
   Роут «Змінити пароль» оператора (с84-B) перевіряв першим, власною копією
   числа. Тут правило винесено в один модуль для ВСІХ шести місць (три роути і
   три форми), щоб копії не розійшлись.

   Модуль чистий (без next/server і без БД): його імпортують і роути, і
   клієнтські форми (реєстрація ставить пароль напряму в GoTrue — серверного
   роуту, який би це перехопив, там немає). */

/** Скільки байт UTF-8 бачить bcrypt у GoTrue. */
export const PASSWORD_MAX_BYTES = 72;

/** Довжина пароля в БАЙТАХ UTF-8 — саме те, що рахує bcrypt. */
export function passwordBytes(password: string): number {
  return new TextEncoder().encode(password).length;
}

/** Чи відхилить сервер входу цей пароль як задовгий. */
export function passwordTooLong(password: string): boolean {
  return passwordBytes(password) > PASSWORD_MAX_BYTES;
}

/** Межа словами — без «байтів» наодинці: кількість літер залежить від абетки
    (цифри й розділові знаки — теж по байту). «До 72 байтів» — родовий після «до». */
export const PASSWORD_LIMIT_HINT = "до 72 байтів (≈72 символи латиницею й цифрами або ≈36 — кирилицею)";

/** Текст відмови для форм з одним полем пароля. Діалог оператора, де полів два,
    каже «Новий пароль задовгий: …» з тією самою підказкою. */
export const PASSWORD_TOO_LONG = `Пароль задовгий: ${PASSWORD_LIMIT_HINT}`;

/** Правило поля «новий пароль» у формах реєстрації та встановлення за посиланням
    (до с85 воно жило двома однаковими виразами в двох компонентах; тоді ж у класі
    великих літер бракувало «Ґ» — ревʼю с85, лінза B). */
export const PASSWORD_RULE = "Мінімум 8 символів, одна велика буква, одна цифра";

/** Помилка непорожнього поля нового пароля (або ""): спершу правило складності,
    потім межа сервера входу. Порожнє поле форма перевіряє сама — у кожної свій
    текст «обовʼязкове». */
export function passwordFieldError(password: string): string {
  if (password.length < 8 || !/[A-ZА-ЯЇІЄҐ]/.test(password) || !/\d/.test(password)) return PASSWORD_RULE;
  return passwordTooLong(password) ? PASSWORD_TOO_LONG : "";
}
