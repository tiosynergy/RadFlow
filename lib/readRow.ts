/* «Не читали» ≠ «немає» — загальне правило для одиночного читання рядка (U-55, с49).
 *
 * ЧОМУ ОКРЕМИЙ ФАЙЛ, а не ще одна доменна функція. `readRoomScheduleRow` (U-13)
 * і `readRoomModality` (U-18) розбирають КОНКРЕТНЕ поле і знають про нього щось
 * своє: у першої легітимним значенням є `schedule = null`, у другої — рядок
 * `OTHER`. Тут доменного знання немає взагалі: питання одне — «рядок є?», і
 * саме тому правило узагальнене. Спроба вигадати йому «домен» дала б третю
 * копію тієї самої трійки if-ів, а копії розʼїжджаються.
 *
 * ЩО ЦЕ ЛІКУЄ. `const { data: cur } = await supabase.from("queue_entries")…`
 * без погляду на `error`: збій читання давав `cur = null`, а `null` у всіх
 * пʼяти місцях означав «немає доступу або запис не знайдено». Тобто транзієнт
 * мережі показувався користувачеві як ВІДМОВА В ДОСТУПІ — діагноз, за яким він
 * піде не туди (питати права замість «повторіть»). Дірки в безпеці тут не було
 * і немає: усі пʼять місць fail-CLOSED, авторизацію робить RPC/RLS. Ціна —
 * чесність, і саме її ми й повертаємо.
 *
 * ⚠️ Правило НЕ вирішує, що робити з незнанням. Воно лише розрізняє три стани;
 * рішення — за місцем виклику, бо ціна різна: там, де читання годує авторизацію
 * (`setQueuePriority`), незнання мусить зупиняти дію, а там, де воно годує лише
 * атрибуцію журналу, — зупиняти НЕ мусить, бо це коштувало б користувачеві дії
 * заради рядка в журналі.
 */

export type RowRead<T> =
  | { known: true; row: T }
  | { known: false; reason: "error" | "missing" };

/** Розібрати відповідь `maybeSingle()`: помилка / порожньо / рядок.
 *
 *  ⚠️ Результат — `NonNullable<T>`, і це не косметика типів. `maybeSingle()`
 *  віддає обʼєднання `{data: Row; error: null} | {data: null; error: Error}`,
 *  тож без `NonNullable` виведений рядок лишався б `Row | null` — і кожне
 *  місце виклику знову писало б `cur?.field`, тобто повертало б рівно ту
 *  необовʼязковість, від якої правило й рятує. */
export function readRow<R extends { data: unknown; error: unknown }>(
  res: R | null | undefined,
): RowRead<NonNullable<R["data"]>> {
  /* ⚠️ Параметр типізовано ВІДПОВІДДЮ (`R`), а не її полем (`{ data: T }`), і це
     не стиль. `maybeSingle()` повертає ОБʼЄДНАННЯ
     `{data: Row; error: null} | {data: null; error: PostgrestError}`; при
     виведенні `T` з поля `data` таке обʼєднання дає `T = never`, і кожне
     звернення `cur.field` падає «Property does not exist on type never».
     Через `R["data"]` тип рядка дістається коректно (заміряно tsc). */
  /* Відповіді немає взагалі (виклик не дійшов / мок збрехав) — це теж незнання,
     а не «немає рядка»: інакше зламаний виклик читався б як порожня таблиця. */
  if (!res) return { known: false, reason: "error" };
  if (res.error) return { known: false, reason: "error" };
  if (res.data === null || res.data === undefined) return { known: false, reason: "missing" };
  /* ⚠️ Масив — це НЕ рядок (ревʼю U-55). `.select()` без `.maybeSingle()` віддає
     `Row[]`, і порожня вибірка приходить як `[]`: без цієї гілки правило
     сказало б «рядок є» на порожньому результаті — рівно та підміна незнання
     фактом, проти якої воно й написане. Типи тут не рятують: `NonNullable<Row[]>`
     — це `Row[]`. Це помилка ВИКЛИКУ, тому `error`, а не `missing`: «не
     знайдено» тут було б другою неправдою. */
  if (Array.isArray(res.data)) return { known: false, reason: "error" };
  return { known: true, row: res.data as NonNullable<R["data"]> };
}
