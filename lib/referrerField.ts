/* ===== RadFlow — поле «Лікар-направник» у картці пацієнта =====

   Найдорожче поле форми: помилка тут невидима оператору, а наслідок важкий —
   запис зникає з порталу направника (той фільтрує по `referrer_id`),
   контекстна крапка не зʼявляється, і відновити звʼязок може лише адмін.

   КЛАС ІНЦИДЕНТУ с31. `referrer_id` перезбирався пошуком по РЯДКУ
   (`docs.find(d => d.name === form.doctor)`) на КОЖНОМУ збереженні — і правка
   ПІБ ПАЦІЄНТА тихо клала null, бо в профілі стояло «Заставська··Марія»
   (подвійний пробіл), а в записі «Заставська·Марія». Відтоді вибір живе
   КЛЮЧЕМ (`r-<id>` / `d-<id>` / ""), а патч іде лише тоді, коли оператор
   СПРАВДІ рухав це поле.

   ⚠️ Помилки СИМЕТРИЧНІ, тому предикат перевіряється з обох боків: не
   написати патч, коли треба (щойно виправлене імʼя лишається старим — дефект
   с43), і написати, коли не треба (звʼязок рветься — інцидент с31).

   Правило живе ТУТ, а не всередині JSX, бо компонентних тестів у проєкті
   немає: vitest працює в `environment: "node"` і за конвенцією
   `vitest.config.ts` тестує лише чисту логіку `lib/*`. Умова, ціна якої —
   загублене направлення, мусить бути в тестованому місці.
   Сторож — `tests/referrerField.test.ts`.

   ⚠️ ВИНЕСЕНО НЕ ВСЕ, і мовчати про це не можна. Того ж класу і тієї ж ціни
   гейт автовибору після «＋ Додати лікаря» (`PatientEditModal`: не чіпати
   вибір, якщо запис уже привʼязаний до направника або тримає нерозпізнане
   імʼя) досі живе в JSX і не покритий. Складання самого списку опцій —
   нормалізація імен, дедуп, початковий ключ, fail-closed `refUnresolved` —
   теж: а це КОРІНЬ інциденту с31. Обидва — у беклозі (ревʼю с44, р.2). */

/** «Залишити як є» для `doctor`, якого немає ні серед направників, ні в
    довіднику (напр. лікаря прибрали з довідника). Окремий ключ, а НЕ порожній
    рядок: інакше «не чіпати» і «очистити» зливаються, і довільний текст стає
    незмивним (ревʼю с31, р.1). */
export const KEEP_KEY = "keep";

/** Стан поля на момент «Зберегти». */
export type ReferrerFieldState = {
  /** запис внесено САМИМ направником → поле лише для читання */
  lockDoctor: boolean;
  /** направник Є, але його картка недоступна цій ролі (RLS) → fail-closed */
  refUnresolved: boolean;
  /** поточний вибір селекта */
  docKey: string;
  /** вибір, з яким картку відкрили */
  origDocKey: string;
  /** щойно виправлено ІМʼЯ поточно обраного лікаря довідника (с43) */
  docDirty: boolean;
};

/**
 * Чи має «Зберегти» переписати направника запису.
 *
 * `lockDoctor` / `refUnresolved` — заборона: поле в цих станах узагалі не
 * редагується, і мовчазний патч відчепив би направлення користувачеві, який
 * навіть не може його повернути.
 * `KEEP_KEY` — «залишити як є»: довільний текст `doctor` не чіпаємо.
 * Далі — рух ключа АБО `docDirty`: перше означає «оператор обрав іншого»,
 * друге — «оператор виправив імʼя ТОГО САМОГО лікаря довідника, і воно має
 * доїхати в запис, хоч ключ не рухався» (с43).
 */
export function shouldPatchReferrer(s: ReferrerFieldState): boolean {
  if (s.lockDoctor || s.refUnresolved) return false;
  if (s.docKey === KEEP_KEY) return false;
  return s.docKey !== s.origDocKey || s.docDirty;
}

/** Опція селекта; для патча потрібні лише ключ та імʼя. */
export type ReferrerOption = { key: string; name: string };

/** Що саме лягає в `queue_entries`. */
export type ReferrerPatch = { doctor: string | null; referrer_id: string | null };

/**
 * Значення патча для обраного ключа.
 * `""` (не вказано) і невідомий ключ → обидва поля null, тобто «очистити».
 * Лікар довідника (`d-`) звʼязку не має взагалі: `referrer_id` завжди null,
 * імʼя їде ТЕКСТОМ — у картки довідника немає акаунта, приєднувати нічого.
 */
export function referrerPatchFor(docKey: string, docs: ReferrerOption[]): ReferrerPatch {
  const sel = docs.find((d) => d.key === docKey);
  return {
    doctor: sel ? sel.name : null,
    referrer_id: sel && sel.key.startsWith("r-") ? sel.key.slice(2) : null,
  };
}
