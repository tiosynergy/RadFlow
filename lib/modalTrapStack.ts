/* ===== RadFlow — стек активних пасток фокуса =====
   Аудит с46, U-8. `useModalA11y` вішає keydown на DOCUMENT у фазі capture. Поки
   вікно одне — все добре. Коли поверх нього відкривається вкладене, слухачів
   стає ДВА на одному вузлі, і `stopPropagation` між ними не працює (потрібен
   stopImmediatePropagation, та й порядок слухачів — це порядок реєстрації, а не
   порядок вікон). Наслідок: Esc у вкладеній формі закривав ВСЕ дерево разом із
   незбереженими правками, а Tab перехоплювався двічі й замикав фокус на двох
   елементах — відказ WCAG 2.1.2 рівня A.

   Штатний запобіжник — параметр `active`, яким батько глушить себе сам (правило
   с43). Він лишається головним. Але його ЗАБУЛИ, і не в одному місці — тому тут
   страховка на рівні хука: клавіші обробляє лише ВЕРХНЯ пастка.

   ⚠️ «Верхня» = взята ОСТАННЬОЮ. Це вірно, бо вкладене вікно завжди зʼявляється
   ПІЗНІШЕ: його малює зміна стану в батьку. Якби двоє вікон монтувались одним
   комітом, React виконав би ефекти знизу вгору і «верхнім» став би батько —
   саме тому `active` лишається обовʼязковим за конвенцією, а не скасовується.

   КОНТРАКТ — навмисно handle, а не три вільні функції (ревʼю с46 р2, F5). Три
   функції над числом дозволяли цілі класи помилок: узяти id і забути
   зареєструвати, зняти чужий id, зняти свій не в очищенні ефекту. Тут узяття і
   реєстрація — одна дія, зняти можна лише СВОЮ пастку і лише через власний
   handle, повторне зняття — no-op. `Symbol` замість числа: підробити або
   переплутати нічим. */

const stack: symbol[] = [];

export type Trap = {
  /** Чи ця пастка зараз головна — тобто чи їй обробляти клавіші. */
  isTop(): boolean;
  /** Зняти пастку. Ідемпотентно: повторний виклик нічого не робить. */
  release(): void;
};

/** Узяти пастку. Реєстрація відбувається ТУТ — стану «взяв, але не поклав» немає. */
export function acquireTrap(): Trap {
  const id = Symbol("modal-trap");
  stack.push(id);
  return {
    /* Порожній стек → true: одиночне вікно, яке чомусь не зареєструвалось, має
       працювати, а не мовчати. Ціна помилки тут — «Esc спрацював», а не
       клінічна, тож fail-open саме в цей бік. */
    isTop: () => stack.length === 0 || stack[stack.length - 1] === id,
    /* Знімаємо ЗА ЗНАЧЕННЯМ, не з вершини: батько може деактивуватись
       (`active=false`), поки дитина ще відкрита — тобто не завжди останнім.
       Звідси ж і ідемпотентність: після першого зняття `lastIndexOf` дає −1, а
       підробити або повторно покласти цей Symbol нізвідки. Окремий прапорець
       `released` тут був би мертвим кодом — його прибрано після того, як
       фальсифікація показала, що жоден тест на нього не реагує. */
    release() {
      const i = stack.lastIndexOf(id);
      if (i >= 0) stack.splice(i, 1);
    },
  };
}

/** Для тестів: знімок стека (КОПІЯ — щоб тест не міг зіпсувати живий стан). */
export function activeTraps(): readonly symbol[] {
  return stack.slice();
}

/** Для тестів: чистий стан між кейсами. У застосунку не викликається. */
export function resetTraps(): void {
  stack.length = 0;
}
