/** Базова затримка аварійного поллінга і стеля — ті самі, що були в хуку. */
export const POLL_BASE_MS = 8000;
export const POLL_MAX_MS = 60000;

/**
 * Скільки сокет має прожити, щоб вважатись СТАБІЛЬНИМ.
 *
 * ⚠️ Замір, що завів це число: `stopPolling()` скидав `pollDelay` у 8 с на
 *    КОЖНОМУ `SUBSCRIBED`. При дребезгу сокета (SUBSCRIBED на пів секунди →
 *    CLOSED → знову) backoff ніколи не розганявся, і клієнт бив у Supabase
 *    повним `callAll` кожні 8 с — тобто рівно в той момент, коли сервісу
 *    найгірше. 30 с — це «підписка справді трималась», а не блимнула.
 */
export const SOCKET_STABLE_MS = 30000;

/**
 * Мінімальний зазор між двома «поверненнями у вкладку».
 *
 * ⚠️ Замір, що завів це число: повернення у вкладку приходить ДВОМА подіями —
 *    `visibilitychange` (visible) і `focus`, — і хук слухав обидві одним
 *    обробником без дедуплікації. Тобто кожне повернення давало ДВА повні
 *    `callAll`; на дошці черги це до шести `router.refresh()` замість трьох.
 *    Секунда з запасом перекриває розрив між двома подіями браузера і при
 *    цьому не заважає людині, яка свідомо перемикається туди-сюди.
 */
export const RETURN_DEDUPE_MS = 1000;

/**
 * Чи виконувати перезапит на «повернення у вкладку».
 *
 * @param lastAt коли востаннє вже перезапитували через повернення (`null` — ще жодного разу)
 * @param now    поточний момент
 * @param gapMs  мінімальний зазор
 */
export function shouldRefetchOnReturn(
  lastAt: number | null,
  now: number,
  gapMs: number = RETURN_DEDUPE_MS
): boolean {
  if (lastAt === null) return true;
  /* ⚠️ Годинник може стрибнути назад (ручний переклад, синхронізація NTP).
     Відʼємна різниця — це НЕ «щойно перезапитували»: fail-open, бо ціна
     зайвого перезапиту менша за ціну застиглого екрана. */
  const dt = now - lastAt;
  if (dt < 0) return true;
  return dt >= gapMs;
}

/** Наступний крок аварійного backoff. */
export function nextPollDelay(prev: number, maxMs: number = POLL_MAX_MS): number {
  const base = Number.isFinite(prev) && prev > 0 ? prev : POLL_BASE_MS;
  return Math.min(Math.round(base * 1.5), maxMs);
}

/**
 * Чи скидати накопичений backoff у базове значення.
 *
 * Скидаємо ЛИШЕ якщо підписка протрималась довше за поріг: інакше дребезг
 * сокета тримав би клієнта на восьмисекундному поллінгу вічно.
 *
 * @param subscribedAt коли прийшов `SUBSCRIBED` (`null` — підписки ще не було)
 * @param now          момент обриву
 */
export function shouldResetBackoff(
  subscribedAt: number | null,
  now: number,
  stableMs: number = SOCKET_STABLE_MS
): boolean {
  if (subscribedAt === null) return false;
  const lived = now - subscribedAt;
  /* Стрибок годинника назад робить `lived` відʼємним — це не доказ
     стабільності, тож НЕ скидаємо (fail-closed саме тут: зайвий скид
     повертає клієнта до частого поллінга, а це шкодить серверу). */
  if (lived < 0) return false;
  return lived >= stableMs;
}
