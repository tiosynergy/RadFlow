/* ===== CSV для Excel в українській локалі — ОДИН писач із захистом (с79, Н-10) =====

   Формат — як у CSV дашборда CEO до с79: BOM (інакше Excel читає UTF-8 як
   cp1251 і кирилиця стає «кракозябрами»), роздільник `;` (у локалі uk-UA кома
   — десятковий знак, і Excel кому як роздільник не прийме), кожна клітинка в
   лапках, лапки всередині подвоєно, рядки через \n.

   ⚠️ ФОРМУЛЬНА ІНʼЄКЦІЯ. Значення, яке Excel/LibreOffice/Google Sheets
   прочитає як формулу, отримує апостроф попереду. Предикат НЕ свій —
   `isFormulaLike` з lib/xlsx.ts (= + - @ TAB CR і їхні повноширинні двійники):
   xlsx-експорт пошуку і CSV дашборда вважають «формулою» одне й те саме.
   До с79 CSV дашборда екранував лише = + - @ — без TAB і CR (знахідка Н-10).

   ⚠️ LF (\n) — додатково до спільного предиката, лише тут. У переліку OWASP
   його немає, але це той самий клас, що TAB і CR: керівний пробільний
   префікс, який імпортер CSV може обрізати перед розбором (опції обрізки
   пробілів в імпорті табличних редакторів) — і тоді `\n=HYPERLINK(…)` стає
   формулою. У xlsx такого кроку немає (клітинка — inline string без
   імпортера), тож спільний предикат не чіпаємо. Ціна — апостроф перед
   легітимним значенням, що починається з переносу рядка; у ПІБ і назвах
   процедур такого не буває.

   ⚠️ ПЕРЕВІД РЯДКА ВСЕРЕДИНІ КЛІТИНКИ (ревʼю с79, L-1). У CSV він законний
   (клітинка в лапках), але імпортер з ІНШИМ роздільником (LibreOffice з
   комою замість `;`) губить межі лапок — і друга половина клітинки стає
   новим записом, тобто ЖИВОЮ формулою: нотатка «Консультація⏎=HYPERLINK(…)»
   давала клікабельне посилання (замір ревʼюера). Тому CR/LF усередині
   значення замінюються пробілом: один запис = один фізичний рядок файлу.
   Гард перевіряється ДО заміни — провідні CR/LF так само дають апостроф.

   NUL вирізається до гарда: LibreOffice викидає його перед розбором, і
   «␀=1+1» ставав формулою (та сама проба ревʼюера). З Postgres text NUL не
   приходить (тип його не приймає), але писач спільний — дешевше закрити.

   ⚠️ КОМА І TAB УСЕРЕДИНІ КЛІТИНКИ (ревʼю с80, L-1 — замір ревʼюера в
   LibreOffice 24.2). Файл, відкритий із КОМОЮ як єдиним роздільником (а наш —
   `;`) і з увімкненим «Evaluate formulas», губить межі лапок: хвіст клітинки
   після коми стає ПОЧАТКОМ нової клітинки, і «Іванов,=2+3» давав живу формулу
   (`of:=2+3`) — ПІБ і телефон вводить і направник, тобто зовнішня сторона. Те
   саме з TAB при імпорті з роздільником TAB. Тому: TAB усередині → пробіл
   (разом із CR/LF), а знак формули, що стоїть одразу після коми (пробіли між
   ними не рятують — імпорт їх обрізає), отримує апостроф: «Іванов,'=2+3».
   Ціна — апостроф у легітимному «…, -5» чи «…, +380…»; на проді 25.09 значень
   із комою чи TAB у ПІБ, телефоні й нотатці — нуль (замір ревʼюера).

   Межа (свідома): провідний ЗВИЧАЙНИЙ пробіл перед `=` не екрануємо — його
   немає в переліку OWASP, а клітинка в лапках із пробілом попереду лишається
   текстом навіть з обрізкою пробілів в імпорті (замір ревʼюера в LibreOffice).
   Розширити — одна умова в csvNeedsGuard. */

import { isFormulaLike } from "@/lib/xlsx";

export const CSV_BOM = "\uFEFF";
export const CSV_SEP = ";";
/** NUL — керівний символ, якого немає в жодному легітимному значенні. */
const NUL_RE = /\u0000/g;

/** Значення, перед яким CSV ставить апостроф (див. шапку: спільний предикат + LF). */
export function csvNeedsGuard(s: string): boolean {
  return isFormulaLike(s) || s.startsWith("\n");
}

/** Знак формули одразу після коми (з можливими пробілами між ними) — див.
    шапку, «КОМА І TAB». Набір знаків — той самий, що в isFormulaLike, крім
    керівних (TAB/CR/LF до цього місця вже стали пробілами). */
const COMMA_FORMULA_RE = /,(\s*)(?=[=+\-@\uFF1D\uFF0B\uFF0D\uFF20])/g;

/** Одна клітинка: null/undefined → порожньо; NUL геть; формула → з апострофом
    (перевірка ДО заміни переводів рядка); CR/LF/TAB усередині → пробіл; знак
    формули після коми → з апострофом; лапки подвоєно; клітинка в лапках. */
export function csvCell(v: unknown): string {
  let s = (v == null ? "" : String(v)).replace(NUL_RE, "");
  if (csvNeedsGuard(s)) s = "'" + s;
  s = s.replace(/[\r\n\t]+/g, " ");
  s = s.replace(COMMA_FORMULA_RE, ",$1'");
  return '"' + s.replace(/"/g, '""') + '"';
}

/** Весь файл: BOM + рядки через \n, клітинки через `;`. */
export function buildCsv(rows: ReadonlyArray<ReadonlyArray<unknown>>): string {
  return CSV_BOM + rows.map((r) => r.map(csvCell).join(CSV_SEP)).join("\n");
}
