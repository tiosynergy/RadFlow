/* ===== RadFlow — «незавершене дослідження» з іншого дня (с24) ================

   ПРОБЛЕМА, яку закриває цей модуль.
   Індекс `queue_one_in_progress_per_room` (0018) — частковий унікальний по
   `room_id where status = 'in_progress'`, і в ньому НЕМАЄ дати. Це правильно
   фізично: у кабінеті одночасно один пацієнт. Але дошка вантажить записи рівно
   одного дня (`.eq("scheduled_date", dayKey)`), тож `currentByRoom` рахується
   тільки по вибраній даті.

   Наслідок: якщо адміністратор забув завершити дослідження, наступного дня
   запис НЕВИДИМИЙ — картка кабінету показує його вільним, кнопка «Викликати в
   кабінет» виглядає активною, клік іде на сервер і падає на 23505
   («У кабінеті вже є пацієнт»). Пацієнта, про якого мова, на дошці немає, і
   куди йти — не сказано.

   ⚠️ Ці записи НЕ можна підмішувати в `entries` дошки: на них зав'язані
   звук перевищення (`useQueueSounds`), таймери кабінетів і лічильники дня.
   Учорашній незавершений запис давав би вічне «перевищено час» і псував
   статистику. Тому вони живуть окремим станом і використовуються лише для
   (а) блокування виклику, (б) видимої підказки з переходом на потрібну дату. */

/** Мінімум полів: ПІБ потрібен для підказки оператору, решта — для переходу. */
export interface StuckStudy {
  id: string;
  room_id: string;
  patient_name: string;
  /** 'YYYY-MM-DD' — рядок з БД, НЕ парсимо в Date (це календарна дата, не момент). */
  scheduled_date: string;
  in_progress_at?: string | null;
}

/**
 * Один незавершений запис на кабінет — так гарантує унікальний індекс 0018.
 * Якщо їх раптом кілька (індекс знято/дані завезли міграцією), лишаємо
 * НАЙСТАРІШИЙ: саме він блокує кабінет довше і про нього треба сказати першим.
 */
export function stuckByRoom(list: readonly StuckStudy[] | null | undefined): Record<string, StuckStudy> {
  const m: Record<string, StuckStudy> = {};
  for (const s of list || []) {
    if (!s?.room_id) continue;
    const prev = m[s.room_id];
    if (!prev || s.scheduled_date < prev.scheduled_date) m[s.room_id] = s;
  }
  return m;
}

/**
 * '2026-08-04' → '04.08'. Різання рядка, а не `new Date()`: scheduled_date —
 * календарна дата клініки, і будь-який парсинг у Date з'їхав би на добу в
 * від'ємних зонах (інваріант проєкту: час — лише через wallNow-сімейство).
 */
export function stuckDateLabel(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || "");
  return m ? `${m[3]}.${m[2]}` : iso || "";
}

/**
 * Причина блокування виклику — текстом, який називає І дату, І пацієнта.
 * Приймає те, що віддає `computeCallBlock` (code: "room_stuck"), а не сам
 * StuckStudy: інакше кожна дошка писала б свою копію рядка, і вони розійшлись би
 * при першій же правці формулювання (ревʼю с24, M3).
 */
export function stuckBlockReason(b: { date: string; name?: string | null }): string {
  return `У кабінеті незавершене дослідження від ${stuckDateLabel(b.date)}${b.name ? ` (${b.name})` : ""} — спершу завершіть його`;
}

/** Причина, коли про «хвости» ще нічого не відомо (fail-closed, ревʼю H1). */
export const STUCK_UNKNOWN_REASON =
  "Дані про незавершені дослідження не оновились — виклик заблоковано, оновіть сторінку";

/**
 * Хвости, які МОЖНА показувати для відкритої дати.
 *
 * Фільтр живе на СПОЖИВАННІ, а не на завантаженні (ревʼю с24, M1): `stuck` і
 * `entries` — два різні запити одного `reload`, тож між ними завжди є кадр, де
 * список належить попередній даті. Без цього фільтра після «← Сьогодні»
 * сьогоднішній ЖИВИЙ пацієнт на кадр показувався б як «незавершений» з
 * посиланням на дату, на якій користувач уже стоїть.
 *
 * Запис із ТІЄЮ Ж датою хвостом не вважається свідомо: він приходить у
 * `entries` як звичайний in_progress, лягає в `currentByRoom` і дає причину
 * `room_busy` — правильнішу, бо пацієнт видимий тут же, у рядку.
 */
export function visibleStuckByRoom(
  list: readonly StuckStudy[] | null | undefined,
  dayKey: string
): Record<string, StuckStudy> {
  return stuckByRoom((list || []).filter((s) => s.scheduled_date !== dayKey));
}

/**
 * Чи невідомо нам про хвости. Стартове `[]` не відрізнити від «хвостів немає»,
 * тому дошка мусить розрізняти «завантажено й порожньо» і «ще/вже не знаємо».
 * Fail-CLOSED: не знаємо — не пускаємо пацієнта в кабінет (ревʼю с24, H1).
 */
export function stuckUnknownOf(loaded: boolean, err: boolean): boolean {
  return !loaded || err;
}

/**
 * Deep-link на дошку тієї дати з розкритим записом. Формат — той самий, що в
 * с22: у URL лише uuid і дата, PII не потрапляє (інваріант приватності).
 */
export function stuckDeepLink(s: StuckStudy, board: "queue" | "radiologist" = "queue"): string {
  return `/${board}?date=${encodeURIComponent(s.scheduled_date)}&entry=${encodeURIComponent(s.id)}`;
}

/**
 * Чи можна викликати наступного пацієнта в кабінет.
 * `current` — запис, що зараз у кабінеті ЗА ВИБРАНУ дату; `stuck` — незавершений
 * з іншої дати. Блокує будь-який з них: індекс 0018 однаково не дасть другий
 * in_progress, і краще сказати про це ДО кліку, ніж ловити 23505 після.
 */
export function canCallIntoRoom(current: unknown, stuck: unknown): boolean {
  return !current && !stuck;
}
