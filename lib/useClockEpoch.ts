"use client";

/* ===== RadFlow — «годинник щойно стрибнув» як сигнал для React (U-70) =====

   ЧОМУ ХУК, А НЕ ОПИТУВАННЯ. Поправка на зсув годинника (Ф4-8) приземляється
   асинхронно, через сотні мілісекунд після монтування. Дошки фіксують
   `selectedDate` ПЕРШИМ рендером, а «сьогодні» перераховують кожен рендер:
   якщо поправка перетинає північ клініки, `today` їде вперед, зафіксована дата
   лишається — і дошка МОВЧКИ стає архівом («Викликати» заблоковано, звуки
   вимкнено, записів нового дня в зрізі немає). Опитування таймером тут не
   годиться: між приземленням поправки і найближчим тіком дошки (20 с) вона вже
   показувала б не той день.

   `useSyncExternalStore` — саме той інструмент: зовнішнє джерело (модульна
   змінна в lib/serverClock.ts) і підписка на його зміни. Серверний знімок — 0:
   на сервері зсув не вимірюється НІКОЛИ (модульна змінна там спільна між
   запитами, див. захист в applyClockEstimate), тож будь-яке інше значення
   означало б розбіжність гідратації. */

import { useSyncExternalStore } from "react";
import { clockEpoch, subscribeClock } from "./serverClock";

/** Номер поточної «епохи» годинника. Змінюється рівно тоді, коли `serverNow()`
    стрибнув; сам по собі не використовується — важлива ПОДІЯ зміни. */
export function useClockEpoch(): number {
  return useSyncExternalStore(subscribeClock, clockEpoch, () => 0);
}
