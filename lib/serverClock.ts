/* ===== RadFlow — зсув годинника браузера відносно годинника БАЗИ (Ф4-8) =====

   ЧОМУ. `in_progress_at` ставить Postgres, а «скільки минуло» рахував браузер
   через `Date.now()`. Корекції зсуву в проєкті не було взагалі. ПК реєстратури
   без NTP, що поспішає на 8 хвилин: кільце таймера стартує з 27:00 замість
   35:00, «критичне» червоне настає на 8 хв раніше, звук перевищення пищить за
   8 хвилин ДО реального кінця вікна кабінету. Зворотний зсув дає дзеркальну
   відмову — перевищення не спрацює НІКОЛИ.

   АВТОРИТЕТ — `now()` БАЗИ, а не годинник Vercel: саме база ставить
   `in_progress_at` і саме нею рахують вікна гарди (0129). Джерело —
   `public.server_now()` (міграція 0169).

   ЩО ТУТ Є І ЧОГО НЕМАЄ. Тут — уся АРИФМЕТИКА (вибір проби, RTT, поріг довіри)
   і сам зсув. Мережі тут немає: проби приносить `components/ServerClockSync.tsx`,
   а ця арифметика покрита викликом у `tests/serverClock.test.ts`. Розділення
   не косметичне — інакше правило «коли пробі можна вірити» перевірялось би
   лише через мок мережі, тобто фактично не перевірялось.

   ФОЛБЕК — СТАТУС-КВО, і це названо свідомо. Поки зсув не виміряно (перші
   мілісекунди після завантаження, відсутня сесія, стара база без 0169, збій
   мережі), зсув = 0 і все рахується РІВНО як до пакета — за годинником
   браузера. Це не «fail-open, який ми додали»: це та сама поведінка, що була,
   і вона не погіршується від того, що поруч зʼявився вимірювач.
   ⚠️ Саме тому тут НЕМАЄ «блокуємо дію, поки годинник невідомий»: таймер і звук
   не приймають рішень про дані, а гейт на невідомий годинник вимкнув би
   дошку на кожному холодному старті. Рішення про дані ухвалює сервер.

   ⚠️ ЗСУВ ЗАСТОСОВУЄТЬСЯ КРОКОМ, А НЕ ЗГЛАДЖУВАННЯМ, і це названо (U-71).
   `serverNow()` — це `Date.now() + _offsetMs`, тож у момент першої поправки
   кільце таймера один раз стрибає і може піти НАЗАД. Класичні NTP-клієнти
   правлять час згладжуванням саме тому, що показуване значення не має права
   йти назад. Тут обрано простоту: стрибок стається щонайбільше раз за захід,
   а альтернатива — власний slew-контур, який доведеться відлагоджувати без
   компонентних тестів. Споживач, якому стрибок ламає ЗНІМОК минулого стану
   (базова лінія звуків), дізнається про нього з `clockEpoch()`. */

/** Одна проба.
    t0/t1 — `Date.now()` ДО і ПІСЛЯ запиту (стінний годинник, який ми й міряємо);
    mono0/mono1 — `performance.now()` тих самих двох моментів (МОНОТОННИЙ
    годинник, який не переводять);
    serverMs — час бази з відповіді, мс епохи. */
export type ClockSample = { t0: number; serverMs: number; t1: number; mono0: number; mono1: number };

/** Проба, чий RTT більший за це, вважається неінформативною і відкидається.
    Невизначеність зсуву не менша за rtt/2, тож проба з RTT 10 с не здатна
    довести зсув у 3 с — а саме такі зсуви ми й ловимо. */
export const CLOCK_MAX_RTT_MS = 2000;

/** Наскільки стінний годинник має право розійтись із монотонним ЗА ЧАС ОДНОГО
    запиту. Більша розбіжність означає, що `Date.now()` стрибнув просто посеред
    проби — і тоді (t0+t1)/2 не «середина вікна», а середнє двох різних епох. */
export const CLOCK_MAX_MONO_DRIFT_MS = 250;

/** Зсув, менший за це, не застосовуємо: він у межах похибки самого вимірювання
    і лише додав би тремтіння в UI (кільце смикалось би на секунду туди-сюди).
    Дефект, заради якого писався пакет, — хвилини, а не десяті секунди. */
export const CLOCK_MIN_APPLY_MS = 1000;

/** Скільки живе прийнята оцінка. Поки вона свіжа, гірша проба її не заміняє;
    після цього годинник міг реально поїхати, і свіжий замір важливіший за
    вузький RTT. */
export const CLOCK_STALE_MS = 5 * 60 * 1000;

/** НАЙГІРША помилка ЗАСТОСОВАНОГО зсуву, у мілісекундах.

    ⚠️ Це виведення довелось переписати: перша редакція (U-70) рахувала лише
    `CLOCK_MAX_RTT_MS/2` і давала вдвічі меншу цифру. Знайшло ревʼю Б, перевірено
    особисто. Складові:
      • `CLOCK_MIN_APPLY_MS` — вимірювання, менше за секунду, ми ОБНУЛЯЄМО. Тож
        справжній зсув до 1 с може лишитись НЕ виправленим, і це не «похибка
        вимірювання», а свідоме рішення, яке теж треба закласти;
      • `CLOCK_MAX_RTT_MS / 2` — невизначеність самої проби (асиметрія плечей);
      • `CLOCK_MAX_MONO_DRIFT_MS / 2` — стінний годинник має право розійтись із
        монотонним у межах порога, і половина цієї розбіжності лягає на середину
        вікна запиту.
    Разом: 1000 + 1000 + 125 = 2125 мс.
    ⚠️ Сюди НЕ входить дрейф ПК між перезамірами і застрягла оцінка після сну —
    перше практично мале, друге закрите правилом «стара оцінка не тримається»
    в applyClockEstimate. Обидва названі там, де живуть. */
export const CLOCK_WORST_ERROR_MS =
  CLOCK_MIN_APPLY_MS + CLOCK_MAX_RTT_MS / 2 + CLOCK_MAX_MONO_DRIFT_MS / 2;

export type ClockEstimate = { offsetMs: number; rttMs: number };

/* ⚠️ ЧОМУ RTT МІРЯЄТЬСЯ МОНОТОННИМ ГОДИННИКОМ (знахідка ревʼю Б, HIGH).
   Перша редакція рахувала `rtt = t1 - t0` тим самим `Date.now()`, який і
   перевіряє. Наслідок був протилежний задуманому: якщо ОС крокнула годинником
   НАЗАД на J посеред запиту тривалістю R, виміряний RTT дорівнював R − J —
   тобто зіпсована проба виглядала ШВИДШОЮ і вигравала відбір «за найменшим
   RTT». R = 8 с із кроком J = 7 с давала «rtt = 1000» і помилку 3,5 с; запит,
   що провисів, поки ноутбук спав, — помилку в хвилини. Перевірка `rtt < 0`
   ловила лише кроки БІЛЬШІ за тривалість запиту.
   `performance.now()` монотонний за специфікацією і переводом годинника не
   зачіпається, тож тепер: тривалість беремо з нього, а розбіжність
   стінного і монотонного відліків за час проби (|(t1−t0) − (mono1−mono0)|) і
   Є детектором стрибка. Проба зі стрибком відкидається цілком.
   Це не теоретичний випадок: `ServerClockSync` навмисно міряє на
   `visibilitychange`, тобто саме тоді, коли ОС найімовірніше підтягне NTP. */

/** ЧИСТА арифметика: найкраща оцінка зсуву з набору проб, або null.
    Правило NTP: беремо пробу з НАЙМЕНШИМ RTT (у неї найвужча невизначеність),
    а не середнє — середнє по пробах із різним RTT гірше за найкращу пробу.
    offset = serverMs − (t0 + t1) / 2. */
export function offsetFromSamples(
  samples: readonly ClockSample[] | null | undefined,
  maxRttMs: number = CLOCK_MAX_RTT_MS
): ClockEstimate | null {
  let best: ClockEstimate | null = null;
  for (const s of samples ?? []) {
    if (!s) continue;
    const { t0, serverMs, t1, mono0, mono1 } = s;
    if (!Number.isFinite(t0) || !Number.isFinite(serverMs) || !Number.isFinite(t1)) continue;
    if (!Number.isFinite(mono0) || !Number.isFinite(mono1)) continue;
    const rtt = mono1 - mono0;                 // монотонна тривалість запиту
    if (rtt < 0 || rtt > maxRttMs) continue;
    // Стінний годинник стрибнув посеред проби → середина вікна безглузда.
    if (Math.abs((t1 - t0) - rtt) > CLOCK_MAX_MONO_DRIFT_MS) continue;
    if (best === null || rtt < best.rttMs) {
      best = { offsetMs: serverMs - (t0 + t1) / 2, rttMs: rtt };
    }
  }
  return best;
}

/** ЧИСТИЙ розбір значення `server_now()` з PostgREST у мс епохи, або NaN.
    ⚠️ Живе ТУТ, а не в компоненті (знахідка ревʼю Б, HIGH): за межу з мережею
    винесли не мережу, а перетворення значення на число — тобто саме те, що
    може мовчки дати правдоподібне, але невірне число.
    Вимога явної зони не косметична. `to_json(timestamptz)` віддає
    '2026-08-31T10:00:00.123456+00:00'; якщо колись функцію перепишуть як
    `now() at time zone 'utc'` (а це та сама ідіома, що в гардах 0129), тип
    стане `timestamp`, зона зі стрічки зникне — і ECMAScript трактує таку форму
    як ЛОКАЛЬНИЙ час. У зоні клініки Europe/Kyiv це дало б «зсув» рівно на
    3 години: число скінченне, RTT не зачеплений, усі пороги пройдені. */
export function parseServerTime(value: unknown): number {
  if (typeof value !== "string") return NaN;
  const s = value.trim();
  // Явна зона: 'Z' | '+HH', '+HH:MM', '-HHMM' у кінці — після часової частини.
  if (!/(?:Z|[+-]\d{2}(?::?\d{2})?)$/i.test(s)) return NaN;
  const ms = Date.parse(s);
  return Number.isFinite(ms) ? ms : NaN;
}

/* ===== Стан модуля ===== */

let _offsetMs = 0;
let _known = false;
let _rttMs = Number.POSITIVE_INFINITY;
let _measuredAtMono = Number.NEGATIVE_INFINITY;
let _measuredAtWall = Number.NEGATIVE_INFINITY;
let _epoch = 0;

/** Зсув «база − браузер» у мс. 0, поки не виміряно. */
export function clockOffsetMs(): number { return _offsetMs; }

/** Чи вимірювався зсув успішно хоч раз. Для діагностики і сторожів; ЛОГІКА
    продукту на цьому не будується — див. «фолбек — статус-кво» в шапці. */
export function clockOffsetKnown(): boolean { return _known; }

/** RTT прийнятої оцінки (мс). Infinity, поки проб не було. */
export function clockRttMs(): number { return _rttMs; }

/** Лічильник ЗМІН зсуву. Росте лише тоді, коли `serverNow()` реально
    стрибнув. Потрібен споживачам, які тримають ЗНІМОК минулого стану і
    порівнюють його з поточним: після стрибка такий знімок знятий іншим
    годинником, і різниця між ним і «зараз» більше не є плином часу.
    Перший споживач — базова лінія звуків (`lib/useQueueSounds.ts`): без цього
    приземлення поправки читалось диференціалом як справжнє перевищення і
    давало звук на дослідження, яке простроченим було вже на відкритті. */
export function clockEpoch(): number { return _epoch; }

/* Підписка на ЗМІНУ зсуву (U-70). Потрібна тим, хто зафіксував похідну від
   «зараз» у стані і не переживе тихого стрибка — перший такий споживач
   `selectedDate` дошок: якщо поправка перетинає північ клініки, «сьогодні»
   їде вперед, а зафіксована дата лишається, і дошка мовчки стає архівом.
   Опитувати `clockEpoch()` таймером тут не годиться: між приземленням
   поправки і найближчим тіком (20 с) дошка вже показувала б не той день. */
const _listeners = new Set<() => void>();
export function subscribeClock(fn: () => void): () => void {
  _listeners.add(fn);
  return () => { _listeners.delete(fn); };
}

/** «Зараз» за годинником БАЗИ. Єдина заміна `Date.now()` там, де момент
    порівнюється з тим, що записав сервер (`in_progress_at`, `updated_at`). */
export function serverNow(): number { return Date.now() + _offsetMs; }

/** Монотонний «зараз» — для порівняння віку оцінок. Виносимо окремо, щоб
    арифметику можна було перевірити викликом у середовищі без performance. */
function monoNow(): number {
  return typeof performance !== "undefined" && typeof performance.now === "function"
    ? performance.now()
    : Date.now();
}

/** Прийняти оцінку. Повертає true, якщо зсув ЗМІНИВСЯ.

    ⚠️ ГІРША ОЦІНКА НЕ ЗАМІНЯЄ КРАЩУ (знахідка ревʼю Б, MEDIUM). Перша редакція
    писала будь-яку оцінку, і при кількох паралельних заходах (швидке
    перемикання вкладок) вигравала та, що фінішувала ОСТАННЬОЮ: пачка з
    найкращою пробою 1900 мс затирала пачку з 40 мс, а відбір за мінімальним
    RTT працював лише всередині пачки й викидався між пачками. Гірше: невдала
    пачка могла СКИНУТИ вже застосовану восьмихвилинну поправку через поріг
    `CLOCK_MIN_APPLY_MS`. Тепер оцінка приймається, лише якщо вона не гірша за
    чинну — або чинна вже застаріла (годинник міг реально поїхати).

    ⚠️ Тільки в браузері. Модульна змінна на сервері шарилась би між запитами
    різних користувачів — той самий клас, що застережений у setClinicTz. */
export function applyClockEstimate(est: ClockEstimate | null): boolean {
  if (typeof window === "undefined") return false;
  if (!est || !Number.isFinite(est.offsetMs) || !Number.isFinite(est.rttMs)) return false;
  /* ⚠️ Поріг перевіряється і ТУТ (знахідка ревʼю Б). До цього він жив лише
     дефолтним параметром `offsetFromSamples`, тобто інваріант «застосований
     зсув отриманий із проби не повільнішої за CLOCK_MAX_RTT_MS» у точці
     ЗАСТОСУВАННЯ не тримався — а саме на ньому побудований CLOCK_WORST_ERROR_MS
     і, через нього, слак вікна виклику. */
  if (!(est.rttMs >= 0) || est.rttMs > CLOCK_MAX_RTT_MS) return false;

  const mono = monoNow();
  const wall = Date.now();
  /* ⚠️ Вік оцінки міряємо ОБОМА годинниками і беремо БІЛЬШИЙ (знахідка ревʼю Б).
     `performance.now()` на типових платформах НЕ йде під час сну ноутбука —
     а `visibilitychange` після пробудження це рівно той момент, заради якого
     підписка й існує. З одним лише монотонним віком свіжа й правильна проба
     («ОС підтягнула NTP, зсув 8 хвилин») відкидалась би як «гірша за чинну»,
     бо чинна формально не встигла протухнути. Стінний вік цього не проґавить:
     якщо годинник стрибнув, вік стрибає разом із ним. */
  const stale =
    mono - _measuredAtMono > CLOCK_STALE_MS ||
    Math.abs(wall - _measuredAtWall) > CLOCK_STALE_MS;
  if (_known && !stale && est.rttMs > _rttMs) return false;

  /* Малий зсув не застосовуємо, але факт вимірювання фіксуємо: «поміряли й
     зсуву немає» — це ЗНАННЯ, а не його відсутність. */
  const next = Math.abs(est.offsetMs) < CLOCK_MIN_APPLY_MS ? 0 : est.offsetMs;
  const changed = next !== _offsetMs;
  _offsetMs = next;
  _rttMs = est.rttMs;
  _measuredAtMono = mono;
  _measuredAtWall = wall;
  _known = true;
  if (changed) {
    _epoch++;
    /* Кожен слухач — окремо, з ковтанням: слухач, який кинув, не сміє
       позбавити повідомлення решту. */
    for (const fn of _listeners) { try { fn(); } catch { /* слухач сам винен */ } }
  }
  return changed;
}

/** Скидання — ЛИШЕ для тестів. */
export function resetServerClock(): void {
  _offsetMs = 0;
  _known = false;
  _rttMs = Number.POSITIVE_INFINITY;
  _measuredAtMono = Number.NEGATIVE_INFINITY;
  _measuredAtWall = Number.NEGATIVE_INFINITY;
  _epoch = 0;
}
