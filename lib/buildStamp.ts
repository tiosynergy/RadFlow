import { createHash } from "node:crypto";

/* ===== Штамп збірки (пакет 42, с59) =====

   ЧОМУ ЦЕ ІСНУЄ. Доки сесій 57–59 описували сигнал «збірка доїхала» як
   `/_next/static/<buildId>/_buildManifest.js` → 200. Пакет 41 заміряв: на
   цьому застосунку такого приладу НЕМАЄ — `/login` не несе жодного
   `buildId` (App Router), слова `_buildManifest` у сторінці немає взагалі,
   а id, записаний наприкінці пакета 40, у відданій сторінці відсутній;
   дванадцять кандидатів зі сторінки перевірено як шляхи маніфеста — усі 404.
   Тобто на питання «чи доїхала збірка» відповіді не було ВЗАГАЛІ.

   ⚠️ І старий прилад був сигналом ОДНОГО напрямку: змінився → щось приїхало;
   не змінився → висновку немає. Цей — ДВОСТОРОННІЙ: штамп детермінований
   від коміта, тож очікуване значення рахується ЛОКАЛЬНО з того самого SHA,
   який щойно запушили, і звіряється з тим, що віддає прод. Збіглось —
   доїхав САМЕ цей коміт; не збіглось — ще старий.

   ⚠️ ЧОМУ НЕ САМ SHA. Репозиторій приватний, і віддавати назовні точну
   версію коду — дрібне, але безоплатне розкриття. Для сигналу «той самий
   коміт чи ні» досить будь-якої детермінованої функції від SHA, тож
   віддаємо `sha256(sha)[:12]`: змінюється рівно тоді, коли змінився коміт,
   і не каже НІЧОГО про сам коміт тому, хто SHA не знає.

   ⚠️ FAIL-LOUD, а не тиха порожнеча. Якщо `VERCEL_GIT_COMMIT_SHA` немає
   (у проєкті вимкнено «Automatically expose System Environment Variables»)
   або він кривий — повертаємо `stamp: null` і НАЗВАНУ причину. Мовчазний
   `null` без причини зробив би прилад таким самим невиразним, як старий. */

export type BuildStamp = { stamp: string | null; reason: string | null };

/** Причини — константи, а не літерали в коді: їх пінить тест. */
export const NO_ENV = "no-system-env";
export const BAD_SHA = "bad-sha";

/**
 * Штамп збірки з git-SHA коміта.
 * @param sha `process.env.VERCEL_GIT_COMMIT_SHA` або undefined поза Vercel.
 */
export function buildStamp(sha: string | undefined | null): BuildStamp {
  if (typeof sha !== "string" || sha.length === 0) {
    return { stamp: null, reason: NO_ENV };
  }
  // Рівно 40 hex — повний git-SHA. Скорочений або сміття — це не коміт, і
  // мовчки хешувати його не можна: штамп став би стабільним і БРЕХАВ би.
  if (!/^[0-9a-fA-F]{40}$/.test(sha)) {
    return { stamp: null, reason: BAD_SHA };
  }
  const stamp = createHash("sha256").update(sha.toLowerCase()).digest("hex").slice(0, 12);
  return { stamp, reason: null };
}
