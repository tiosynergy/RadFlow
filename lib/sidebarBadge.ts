/**
 * U-60 — «нуль» і «не знаємо» не мають виглядати однаково.
 *
 * ЩО БУЛО. Бейджі сайдбарів малюються falsy-гейтом (`{n ? <span/> : null}`),
 * тож `0` і «читання впало, значення нема» дають ОДИН І ТОЙ САМИЙ піксель —
 * порожнє місце. Направник, у якого не завантажився лист, бачить рівно те
 * саме, що направник із порожнім листом.
 *
 * ⚠️ ЗАМІР ПРОТИ ДОКА: док називав ОДНЕ місце (бейдж листа в сайдбарі
 *    направника). На дереві їх ТРИ — там же бейдж «Мої направлення»
 *    (`listErr` ігнорувався так само) і `waitCount` у сайдбарі персоналу
 *    (F4-9 захистив його від збою ДРУГОГО читання, лишивши попереднє
 *    значення, але перше читання так і лишає нуль). Це вже вкотре, коли
 *    перелік із дока виявився вужчим за дерево, — тому правило тут знімає
 *    ВЛАСТИВІСТЬ, а не лікує названі місця.
 *
 * ⚠️ МЕЖА: `incidentCount` у сайдбарі персоналу приходить готовим числом із
 *    `QueueBoard` (`liveIncidents.length`) — його стан завантаження сюди не
 *    доходить, і в цьому пакеті він НЕ перевірявся.
 */

/** Чи є значенню віри. */
export type LoadStatus = "loading" | "ready" | "failed";

export type BadgeValue =
  | { kind: "hidden" }
  | { kind: "unknown" }
  | { kind: "count"; value: number };

/**
 * @param okOnce     чи був хоч ОДИН успішний читок (не «спроба скінчилась»)
 * @param lastFailed чи впала ОСТАННЯ спроба
 *
 * ⚠️ `okOnce` СТОЇТЬ ПЕРШИМ, і це контракт F4-9, а не порядок «як вийшло»:
 *    якщо значення колись прочиталось, збій наступного читання лишає його
 *    показаним — застаріле число корисніше за прочерк. «Не знаємо» —
 *    це рівно випадок, коли валідного значення не було НІКОЛИ.
 *
 * ⚠️ І `loading` — НЕ `failed`: інакше бейдж блимав би прочерком на кожному
 *    відкритті сторінки, і «не знаємо» перестало б щось означати.
 */
export function loadStatusOf(okOnce: boolean, lastFailed: boolean): LoadStatus {
  if (okOnce) return "ready";
  return lastFailed ? "failed" : "loading";
}

/**
 * ⚠️ `hidden` для нуля — свідомо: порожній бейдж і є прийнятий вигляд «нікого
 *    немає». Дефект U-60 був НЕ в тому, що нуль ховається, а в тому, що під
 *    тим самим виглядом ховалась незнана величина.
 */
export function badgeOf(status: LoadStatus, value: number): BadgeValue {
  if (status === "failed") return { kind: "unknown" };
  if (status === "loading") return { kind: "hidden" };
  return value > 0 ? { kind: "count", value } : { kind: "hidden" };
}
