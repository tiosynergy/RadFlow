/* ============================================================================
   ОБСЛУГОВУВАННЯ — бекфіл subject_date у позначках, створених ДО 0133

   ВИКОНАНО 2026-08-06 (сесія 27), одразу після накату 0133. Файл лишається
   як СЛІД правки прод-даних: список id, before-образ і команда відкату.

   НАВІЩО. 0131/0132 працювали в проді до накату 0133, тож устигли створити
   позначки без `subject_date`. Такі позначки видно в навігації і на картці,
   але НЕ на міні-календарі — а це виглядає як «календар зламаний» рівно в
   момент першої живої перевірки. Разова правка усуває перехідну когорту.

   BEFORE-ОБРАЗ: у всіх чотирьох рядків subject_date був NULL (перевірено
   dry-run-ом із `raise exception` до застосування).

   ЩО НЕ ЧІПАЄМО:
     • ПРОЧИТАНІ позначки (`seen_at is not null`) — вони вже в історії, на
       календар не впливають, а зміна їхніх полів була б переписуванням
       минулого;
     • позначки без відповідного запису черги і записи без scheduled_date —
       для них дати просто не існує.

   ⚠️ РАЗОВА. Повторний запуск нічого не зробить (умова `subject_date is null`),
   але й сенсу не має: з 0133 дату проставляє сам тригер.
   ============================================================================ */

-- ── ЗАСТОСОВАНО ──────────────────────────────────────────────────────────
update public.user_change_markers m
   set subject_date = q.scheduled_date
  from public.queue_entries q
 where q.id = m.entity_id
   and m.entity_type = 'queue_entry'
   and m.subject_date is null
   and m.seen_at is null
   and q.scheduled_date is not null
   and m.id in (
     '01475bff-2249-49da-8e29-785b0462f4df',   -- queue/status  → 2026-08-06
     'aff178b7-3211-4743-b82d-017bcf4d0957',   -- queue/status  → 2026-08-06
     '7268b925-950d-4fd3-afc0-a68400352e26',   -- queue/record  → 2026-08-07
     '4a6de0ce-c83b-4dab-8efc-e35031ef6e51'    -- queue/record  → 2026-08-07
   );
-- Результат: 4 рядки; після правки жодної непрочитаної позначки черги
-- без дати не лишилось.

