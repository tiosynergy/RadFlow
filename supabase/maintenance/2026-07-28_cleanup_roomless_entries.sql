select (select count(*) from public.queue_entries)                                     as queue_left,
       (select count(*) from public.queue_entries where room_id is null)               as roomless_left,
       (select count(*) from public.queue_entries
         where room_id is null and case_id is null)                                    as roomless_plain,
       (select count(*) from public.audit_log
         where table_name = 'queue_entries' and action = 'delete'
           and at > now() - interval '1 hour')                                         as audit_deletes_1h;
