-- ============================================================================
--
--  ЩО ЧИНИТЬ. Додає до enum-типу `public.modality` три нові модальності:
--    US    — УЗД (ультразвукова діагностика)
--    XRAY  — Рентген (рентгенографія)
--    MAMMO — Мамографія
--  Тип використовують `rooms.modality` та `referral_access.modalities[]`.
--  Раніше було лише MRI / CT / OTHER, тож кабінети УЗД/Рентгена/Мамографії
--  доводилось заводити як «Інше», а гранти направників не могли їх розрізнити.
--
--  ⚠️ БЕЗ транзакційної обгортки. `ALTER TYPE … ADD VALUE` НЕ можна виконувати
--     всередині блоку транзакції / do $$ … $$ (Postgres це відхилить). Тому три
--     окремі оператори верхнього рівня. `IF NOT EXISTS` робить їх ідемпотентними
--     (повторний запуск — тихий no-op), тож обгортка do/exception і не потрібна.
--
--  ⚠️ Нове значення enum НЕ можна ВИКОРИСТОВУВАТИ в тій самій транзакції, де його
--     додали. Тут ми його не використовуємо — лише реєструємо. Політики/RPC не
--     чіпаються (розширення домену зворотно сумісне).
--
--  Порядок у enum: нові значення додаються В КІНЕЦЬ (після OTHER) — на сортування
--  за модальністю ніде не покладаємось, тож позиція значення ролі не грає.
-- ============================================================================

alter type public.modality add value if not exists 'US';
alter type public.modality add value if not exists 'XRAY';
alter type public.modality add value if not exists 'MAMMO';

