-- ============================================================================
-- 0125_slot_grid_guard.sql
-- Сітка 5 хвилин для часу слота запису — тепер інваріант БД (техаудит
-- 2026-07-27, High-1) + нормалізація двох легасі-рядків «HH:MM:SS».
--
-- Контекст. SlotPicker малює сітку з кроком SLOT_STEP = 5 хв (lib/slots.ts), і
-- ВЕСЬ клієнтський флоу видає лише такі часи. Але серверна валідація приймала
-- будь-який коректний HH:MM: '09:03', надісланий повз UI прямо в Server Action
-- (це публічний ендпойнт для будь-якого автентифікованого користувача), сідав у
-- БД. Такий запис «є» — займає час, впливає на busy-слоти — але його НЕ ВИДНО в
-- жодній клітинці сітки: ключі сітки — рядки '09:00'/'09:05', а '09:03' серед
-- них немає. Той самий клас дефекту, що «запис-привид 8:5» (M-1, канон zTime).
--
-- Клієнтське дзеркало — zSlotTime (lib/validation.ts), застосований до слота
-- запису, переносу, кроку кейса і 'to' плану затримок. zTime лишився загальним:
-- робочі години й перерви графіка МОЖУТЬ бути некратними (08:33–13:07 — легально),
-- тому тригер стоїть ТІЛЬКИ на queue_entries.scheduled_time.
--
-- Легасі-дані. У проді два рядки з форматом 'HH:MM:SS' ('11:15:00', '11:45:00',
-- обидва 2026-07-17, старші за валідацію M-1). Хвилини у них кратні 5, але
-- формат ламає все, що порівнює час ЯК ТЕКСТ: ключ у сітці слотів не збігається,
-- а план затримок для їхнього кабінету падає ще на клієнті (from: zTime відкидає
-- '11:15:00'). Нормалізуємо ДО створення тригера.
--
-- Чому тригер, а не CHECK-констрейнт: CHECK валідує і СТАРІ рядки при будь-якому
-- UPDATE рядка (навіть колонок, не повʼязаних із часом) — якби десь лишився
-- off-grid легасі-рядок, його не можна було б навіть скасувати. Тригер на
-- INSERT / UPDATE OF scheduled_time перевіряє лише НОВЕ значення часу: історія
-- живе, а будь-яка нова поява off-grid часу — блокується. (UPDATE OF спрацьовує
-- від ЗГАДКИ колонки — канон; тут це і треба: RPC переносу завжди пише
-- scheduled_time, і нове значення мусить бути на сітці.)
--
-- Порядок викатки: міграція БЕЗПЕЧНА до і після клієнта 0125 (zSlotTime) —
-- клієнт шле лише сіткові часи вже сьогодні. Але нормалізацію легасі-рядків
-- варто накотити ДО наступного плану затримок у кабінеті «Закревського, 9».
--
-- Ідемпотентність: create or replace + drop trigger if exists + update лише
-- рядків, що відповідають патерну 'HH:MM:SS'.
-- ============================================================================

-- ── 1. Нормалізація легасі 'HH:MM:SS' → 'HH:MM' ─────────────────────────────
-- Зрізаємо РІВНО суфікс ':SS' і лише там, де прификс — валідний HH:MM: рядок
-- зовсім іншого формату (якби такий існував) краще побачити в моніторингу, ніж
-- мовчки «полагодити» substring-ом у щось несподіване.
-- Примітка (ревʼю с15, Low-4): цей UPDATE проганяє валідаційні тригери
-- (check_not_during_break / check_room_schedule) для легасі-рядків у активних
-- статусах — якби такий рядок сидів у перервi чи поза графіком, міграція б
-- упала. На проді обидва рядки термінальні/минулі, dry-run — SMOKE_OK.
update public.queue_entries
   set scheduled_time = left(scheduled_time, 5)
 where scheduled_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$';

-- ── 2. Гард сітки ───────────────────────────────────────────────────────────
create or replace function public.guard_slot_grid()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  -- NULL легальний: запис без часу (вейтліст-сток, «потребує переносу»).
  if new.scheduled_time is not null
     and (
       new.scheduled_time !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
       or (split_part(new.scheduled_time, ':', 2)::int % 5) <> 0
     ) then
    raise exception
      'SLOT_GRID: час початку має бути HH:MM і кратним 5 хвилинам (отримано «%»)',
      new.scheduled_time
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

-- Канон 0122 + знахідка цього ж смоуку: default privileges Supabase дають anon
-- execute на КОЖНУ нову функцію, а КРІМ того функції мають неявний EXECUTE для
-- PUBLIC — і revoke від anon його НЕ знімає (has_function_privilege('anon',…)
-- лишався true через PUBLIC). Знімаємо обидва. Тригерну функцію викликає БД від
-- імені власника таблиці, тож на роботу тригера revoke не впливає — гігієна ACL.
revoke execute on function public.guard_slot_grid() from public, anon, authenticated;

drop trigger if exists trg_guard_slot_grid on public.queue_entries;
create trigger trg_guard_slot_grid
before insert or update of scheduled_time on public.queue_entries
for each row execute function public.guard_slot_grid();
