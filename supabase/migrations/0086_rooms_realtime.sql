--
--  ЩО ЧИНИТЬ. Зміни кабінетів (видалення, правка БАЗОВОГО тижневого графіка
--  rooms.schedule через майстер) не долітали до інших ролей у реальному часі:
--  жодна дошка не підписана на `rooms`, а сам список кабінетів приходить SSR-пропом.
--  Інша роль бачила видалений кабінет / старі години в сітці слотів до перезавантаження
--  сторінки. Дані при цьому були в безпеці (0084 check_room_schedule і scheduleBlock
--  читають АКТУАЛЬНИЙ графік з БД), але UI лишався застарілим.
--
--  Тут — серверна половина: додаємо rooms у публікацію supabase_realtime, щоб
--  postgres_changes на кабінетах узагалі надсилалися. Клієнтська половина (підписка
--  дошок + router.refresh) — у компонентах.
--
--  ⚠️ REPLICA IDENTITY FULL — ОБОВʼЯЗКОВО для цього кейсу. Подія DELETE несе лише
--  колонки replica identity (за замовчуванням — тільки PK `id`). Без clinic_id у
--  «старому» рядку і RLS, і фільтр `clinic_id=eq.…` на DELETE не спрацюють → подія
--  ВИДАЛЕННЯ кабінету не дійшла б до підписників (а це головний сценарій скарги).
--  rooms — маленька таблиця, що змінюється зрідка, тож FULL по WAL нічого не коштує
--  (на відміну від queue_entries, де FULL роздував би WAL — там його свідомо немає).
-- ============================================================================

alter table public.rooms replica identity full;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
     where pubname = 'supabase_realtime'
       and schemaname = 'public'
       and tablename = 'rooms'
  ) then
    alter publication supabase_realtime add table public.rooms;
  end if;
end $$;

