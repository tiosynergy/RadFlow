-- ---------------------------------------------------------------------------
--  RadFlow — Міграція 0139
--  RF-03 (Medium зовнішнього аудиту): направник бачив операційний каталог УСІЄЇ
--  клініки замість кабінетів свого гранта.
--
--  Максимальний ЗАСТОСОВАНИЙ на момент написання — 0138.
-- ---------------------------------------------------------------------------
--
--  Живий замір під направником `817b6c78` (2 центри): кабінетів у центрах 9,
--  ДОЗВОЛЕНО грантом 5, а RLS віддавала **9**; послуг 212 із 212; простоїв
--  7 із 7. В UI він при цьому бачить рівно 5 — портал фільтрує сам
--  (`roomsInGrant`, lib/rooms.ts). Тобто правило знову жило ЛИШЕ в клієнті, а
--  прямий PostgREST його обходив: це та сама форма дефекту, що RF-01 у
--  радіолога, тільки для іншої ролі.
--
--  === ОДНЕ ПРАВИЛО НА ВЕСЬ ПАКЕТ ===
--
--  Направник бачить кабінет (і все, що до кабінета привʼязано), якщо кабінет
--
--      (1) у його ГРАНТІ (`referral_access.room_ids`, канон 0029/0137), АБО
--      (2) у ньому стоїть ЙОГО ВЛАСНИЙ рядок — черги чи листа очікування.
--
--  Це множина `auth_referrer_visible_rooms()`. Її застосовуємо ОДНАКОВО до
--  `rooms`, `services` і `incidents`. Перша редакція пакета мала два різні
--  предикати (кабінети — ширший, прайс і простої — вужчий); обидва ревʼю
--  незалежно показали, що розведення коштує дорожче за виграш, — див. розділ
--  «Чому не два правила» нижче.
--
--  `sro_referrer_read` (service_room_overrides) звужений ще в 0111 — саме звідти
--  взято форму «клінічний гейт AND кабінетний гейт»; там же, у шапці 0111,
--  стоїть запис «services свідомо лишаємо на рівні центру», який ця міграція
--  скасовує.
--  ⚠️ Але предикат у 0111 ІНШИЙ — там `auth_referrer_can_book_room`, тобто лише
--  грант, без гілки (2). Для кабінета власного рядка поза грантом направник
--  тепер бачить послуги, а override-и цього кабінета — ні, і каталог збереться
--  з базовими цінами замість переозначених. Практично недосяжно (писати в такий
--  кабінет він усе одно не може), але це РІЗНИЦЯ, а не «той самий зразок» —
--  вирівнювання `sro_referrer_read` винесено окремим пунктом у беклог.
--
--  === ⚠️⚠️ ГОЛОВНА ПАСТКА: базові послуги (`services.room_id is null`) ===
--
--  Канон 0121: `room_id IS NULL` — це БАЗОВА послуга центру, яку успадковують
--  усі кабінети відповідної модальності; `room_id = X` — власна послуга
--  кабінета X. На проді 34 базові і 178 кабінетних.
--
--  Наївне `auth_can_refer(clinic_id) and auth_referrer_can_book_room(room_id)`
--  вбило б продукт: для базової послуги `p_room` = NULL, а хелпер робить
--  `where r.id = p_room` → `exists` = false → у направника зникають УСІ базові
--  послуги. Далі каскадом: `isConfigured()` в `lib/catalog.ts` бачить порожній
--  каталог і мовчки віддає СТАТИЧНИЙ довідник `lib/studies` (чужі ціни й
--  тривалості); серверний гейт `firstClosedService` — так само; а тригер
--  `check_studies_active_catalog` (SECURITY DEFINER, бачить УСІ послуги)
--  відхиляє вставку з `SERVICE_CLOSED`. Направник отримав би «Обрана послуга
--  щойно була вимкнена — оновіть форму» на КОЖНУ спробу запису, і оновлення
--  форми не допомагало б ніколи. Плюс лист очікування без прив'язки до
--  кабінета взагалі не має іншого каталогу, крім базового.
--  Тому гілка `room_id is null` — ОБОВʼЯЗКОВА і не «про всяк випадок».
--
--  === ⚠️ Кабінет ЙОГО ВЛАСНОГО запису має лишатись видимим ===
--
--  `queue_select` (0136) і `waitlist_select` (0138) віддають направнику його
--  рядки по `created_by / referrer_id` БЕЗ перевірки кабінета — і це навмисно
--  (0057: адміністратор може призначити його направником запису в кабінеті, до
--  якого гранта немає; грант могли звузити ВЖЕ ПІСЛЯ бронювання). На проді
--  такий рядок уже є (1 запис у кабінеті поза грантом).
--
--  Якщо звузити рівно до гранта, у нього поїде UI на рядках, які він законно
--  бачить: у «Моїх направленнях» назва кабінета підміниться назвою ЦЕНТРУ і
--  зникне бейдж модальності (`ReferrerBoard`), крок кейса покажеться як
--  «` · —`» (`CaseModal` робить embedded-join `room:room_id(...)`, і на
--  прихованому рядку PostgREST тихо віддає `room: null`), а `RescheduleModal`/
--  `StudyEditModal` втратять графік кабінета і відкотяться на дефолт 08–18.
--  Витоку в гілці (2) немає: `room_id` цього рядка направник уже читає через
--  `queue_select`; політика лише дозволяє відрезолвити `id → name/modality`.
--
--  ⚠️ Гілка (2) НЕ «самообслуговується»: сам створити рядок у кабінеті поза
--  грантом направник не може — `queue_write_referrer` (0057) вимагає
--  `auth_referrer_can_book_room` і в USING, і в WITH CHECK, а
--  `waitlist_write_referrer` (0101) — у WITH CHECK. Тобто розширити собі
--  видимість він не здатен: рядок у чужому кабінеті може зʼявитись лише рукою
--  персоналу центру. Смоук перевіряє це ПОВЕДІНКОВО (зонд a5) — інакше весь
--  пакет тримався б на неназваному інваріанті в чужих міграціях.
--
--  === Чому не два правила (прайс окремо від кабінетів) ===
--
--  Спокуса була така: назву кабінета показати, а прайс — ні. Ціна цього —
--  розсинхрон із тригером: `lib/catalog.ts` у своїй шапці зобовʼязаний бити
--  біт-у-біт з exists-логікою `check_studies_active_catalog`, а тригер —
--  DEFINER і бачить УСІ послуги. У центрі, де базових послуг немає взагалі (на
--  проді це `c79588d6`: 0 базових, 178 кабінетних), для кабінета власного рядка
--  `isConfigured()` перевернувся б у false і резолвер мовчки пішов би на
--  статичний `lib/studies` — чужі ціни й тривалості на власному пацієнті, без
--  жодної ознаки деградації в інтерфейсі. У змішаному центрі було б ще тихіше:
--  каталог «налаштований», але позиції кабінета зникли, і `studyDur`/
--  `studyPrice` віддають статику на конкретній області.
--  Виграшу ж від розведення нема: склад дослідження, ціну й тривалість свого
--  запису направник і так читає — вони лежать снапшотом у `studies` jsonb.
--  Тому правило одне.
--
--  === Межі пакета ===
--
--  • `schedule_overrides` НЕ чіпаємо: рядок там — на КЛІНІКУ і дату, а кабінети
--    лежать усередині jsonb `rooms`. Звузити «по кабінету» без зміни форми
--    таблиці неможливо; витік обмежений тим, що центр у такий-то день працює
--    інакше. Окрема задача, якщо колись знадобиться.
--  • `incidents.room_id` — NOT NULL (перевірено), тож гілка «загальноклінічний
--    простій» не потрібна: аварійна зупинка створює рядки НА КОЖЕН кабінет.
--    Якщо колонку колись зроблять nullable — сюди треба буде додати
--    `room_id is null or …`, інакше такі простої перестануть блокувати сітку.
--  • Грант `room_ids = '{}'` (fail-closed із 0137) після цієї міграції дає нуль
--    кабінетів ПО ГРАНТУ — плюс кабінети власних рядків по гілці (2), плюс УСІ
--    БАЗОВІ послуги центру. Базова гілка усвідомлена: у неї немає кабінета, за
--    яким звужувати, а записати такий направник усе одно нікуди не може
--    (`referrerModalityAllowed`).
--  • ⚠️ Свідомо НЕ покриваємо `reschedule_origin->>'from_room'` (підпис
--    «🔁 Перенесено з …»): це JSON, не FK, і запис за визначенням уже НЕ стоїть
--    у тому кабінеті. Ціна — у підписі зникне назва старого кабінета, якщо той
--    кабінет пізніше вийшов із гранта.
--  • Політики лишаються для тих самих ролей, що були ({public} у rooms/
--    incidents, {authenticated} у services). EXECUTE для anon на новому хелпері
--    видаємо ЯВНО, а не покладаємось на supabase-дефолт (пастка 0122): інакше
--    протухла сесія на {public}-політиці дістала б 42501 замість порожньо
--    (пастка 0073).
--
--  === Клієнтські правки в пакеті ===
--
--  • `ReferrerSidebar` — порожній стан більше не бреше: до 0139 список кабінетів
--    центру був повним, і «немає жодного» означало «центр не заповнив
--    обладнання». Тепер порожньо буває і через грант, і повідомлення розділені.
--  • `ReferralPortal.reschedRooms` — випадайка кабінетів у переносі фільтрується
--    грантом ЯВНО (раніше вона показувала весь центр, і RPC потім відмовляв).

begin;

set local lock_timeout = '3s';

-- ============================================================================
-- 1. Індекс під гілку (2): `waitlist_entries.referrer_id`
-- ============================================================================
-- Хелпер нижче робить пошук рядків листа за `referrer_id`. Індекс на
-- `created_by` є (`waitlist_created_by_idx`), на `referrer_id` — не було, хоча
-- 0138 зробив цю колонку несучою і для `waitlist_select`. Без нього кожен
-- виклик хелпера — seq scan по листу.
-- Свідомо БЕЗ `concurrently`: усередині транзакції воно заборонене, а лист
-- очікування — таблиця на сотні рядків, ShareLock на час побудови непомітний.
-- Якщо колись розростеться — виносити окремою міграцією поза транзакцією.
create index if not exists waitlist_referrer_idx
  on public.waitlist_entries (referrer_id)
  where referrer_id is not null;

-- ============================================================================
-- 2. Хелпер: МНОЖИНА кабінетів, видимих направнику
-- ============================================================================
-- Повертає setof, а не boolean-per-row, свідомо: `x in (select fn())` планувач
-- піднімає в один хешований підплан на запит (канон InitPlan), тоді як
-- `fn(room_id)` з аргументом-колонкою викликається на КОЖЕН рядок. Для `rooms`
-- (одиниці рядків) різниці нема, а `services` читається цілком на кожен SSR
-- порталу і на кожне відкриття модалки переносу — там це 178+ викликів
-- SECURITY DEFINER проти одного.
--
-- SECURITY DEFINER: усередині потрібні `queue_entries`/`waitlist_entries` без
-- їхніх політик (інакше — зайві плани і залежність від чужих правил).
-- ⚠️ Клінічний гейт тут НЕ дублюється: множина може містити кабінет центру, до
-- якого доступ уже відкликано (старі рядки направника лишаються видимими йому
-- по `created_by`). Відсікає це ПЕРШИЙ конʼюнкт кожної політики
-- (`auth_referrer_clinics()` / `auth_can_refer`), де стоїть `status='active'`.
--
-- ⚠️ CTE `me` — не косметика, а ГЕЙТ РОЛІ. Політики направника permissive і
-- OR-яться зі staff/ceo-політиками, а порядок обчислення конʼюнктів вибирає
-- планувальник — тобто цей хелпер може виконатись і для реєстратора. Без `me`
-- гілки (2a)/(2b) зібрали б хеш із УСІХ його `created_by`-рядків (у реєстратора
-- це тисячі) на кожне читання rooms/services/incidents. `exists (select 1 from
-- me)` — некорельований підзапит, обчислюється один раз і для не-направника
-- вимикає обидві дорогі гілки.
--
-- ⚠️ ФУНКЦІЯ ЧИТАЄ `public.rooms` І СТОЇТЬ У ПОЛІТИЦІ НА `public.rooms`.
-- Рекурсії немає ЛИШЕ тому, що вона SECURITY DEFINER від власника таблиці, а на
-- `rooms` не ввімкнено `force row level security`. Якщо колись увімкнуть —
-- БУДЬ-ЯКЕ читання `rooms` впаде з 42P17 (infinite recursion in policy).
create or replace function public.auth_referrer_visible_rooms()
returns setof uuid
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with me as (
    select ra.clinic_id, ra.room_ids
      from public.referral_access ra
     where ra.referrer_id = auth.uid()
       and ra.status = 'active'
  )
  -- (1) кабінети гранта
  select r.id
    from public.rooms r
    join me on me.clinic_id = r.clinic_id
   where me.room_ids is null or r.id = any(me.room_ids)
  union
  -- (2a) кабінети власних рядків черги
  select q.room_id
    from public.queue_entries q
   where q.room_id is not null
     and (q.created_by = auth.uid() or q.referrer_id = auth.uid())
     and exists (select 1 from me)
  union
  -- (2b) …і листа очікування
  select w.room_id
    from public.waitlist_entries w
   where w.room_id is not null
     and (w.created_by = auth.uid() or w.referrer_id = auth.uid())
     and exists (select 1 from me);
$$;

-- ЯВНИЙ грант: політики rooms/incidents лишаються {public}, тож протухла сесія
-- (роль anon) МУСИТЬ мати EXECUTE — інакше замість порожнього списку прилетить
-- 42501 (пастка 0073). Покладатись на supabase-дефолт не можна: він сам по собі
-- пастка 0122 і може бути затиснутий у майбутньому.
grant execute on function public.auth_referrer_visible_rooms() to anon, authenticated;

-- ============================================================================
-- 3. rooms
-- ============================================================================
drop policy if exists rooms_referrer_read on public.rooms;
create policy rooms_referrer_read on public.rooms
  for select using (
    clinic_id in (select public.auth_referrer_clinics())
    and id in (select public.auth_referrer_visible_rooms())
  );

-- ============================================================================
-- 4. services — базові центру + послуги видимих кабінетів
-- ============================================================================
drop policy if exists services_referrer_read on public.services;
create policy services_referrer_read on public.services
  for select to authenticated using (
    public.auth_can_refer(clinic_id)
    and (room_id is null or room_id in (select public.auth_referrer_visible_rooms()))
  );

-- ============================================================================
-- 5. incidents — простої видимих кабінетів
-- ============================================================================
-- Направник читає простої для того, щоб сітка слотів не пропонувала час у
-- зупиненому кабінеті (`slotBlockedByIncidents`). Для кабінета власного запису
-- це теж доречно: зупинка стосується його пацієнта.
drop policy if exists incidents_referrer_read on public.incidents;
create policy incidents_referrer_read on public.incidents
  for select using (
    clinic_id in (select public.auth_referrer_clinics())
    and room_id in (select public.auth_referrer_visible_rooms())
  );

commit;
