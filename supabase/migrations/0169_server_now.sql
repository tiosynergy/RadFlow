-- ---------------------------------------------------------------------------
--  0169 — public.server_now(): годинник СЕРВЕРА для клієнта (Ф4-8)
--
--  ЧОМУ. `in_progress_at` пише Postgres, а «скільки минуло» рахує браузер через
--  Date.now(). Корекції зсуву в проєкті не було взагалі (грепом по
--  skew/serverNow/clockOffset — нуль). ПК реєстратури без NTP, що поспішає на
--  8 хвилин, дає: кільце таймера стартує з 27:00 замість 35:00, «критичне»
--  червоне настає на 8 хв раніше, звук перевищення пищить за 8 хвилин до
--  реального кінця вікна кабінету. Зворотний зсув дає дзеркальну відмову —
--  перевищення не спрацює НІКОЛИ.
--
--  ЧОМУ САМЕ POSTGRES, А НЕ ГОДИННИК VERCEL. Авторитет, який СТАВИТЬ
--  `in_progress_at`, — це `now()` бази. Міряти зсув проти будь-якого іншого
--  годинника означає вводити третю сторону і сподіватись, що вона синхронна.
--  Тому джерело часу тут — та сама функція, що стоїть у гардах (0129: `v_actual
--  := (now() at time zone tz) at time zone 'utc'`).
--
--  ЩО ЦЕ НЕ Є. Функція не «синхронізує годинники» і нічого не виправляє в БД.
--  Вона віддає одне значення; ВСЯ логіка вимірювання (RTT, вибір найкращої
--  проби, поріг довіри) живе в `lib/serverClock.ts` і покрита викликом.
--
--  ⚠️ ПАСТКА 0122 діє і тут, хоча drop-у немає. `create or replace function` у
--     схемі public отримує ДЕФОЛТНИЙ ACL: EXECUTE дістає і PUBLIC, і `anon`.
--     Тому revoke нижче — не косметика, а єдине, що тримає поверхню. Той самий
--     revoke треба повторити при БУДЬ-ЯКОМУ майбутньому пере-створенні.
--     Позитивна і негативна половини ACL пінуються в
--     supabase/smoke/server_now_smoke.sql (anon → 42501, authenticated → успіх).
--
--  ⚠️ ЧОМУ anon ВІДКЛЮЧЕНО, хоча час — не таємниця. Секрету тут справді немає:
--     заголовок `Date:` віддає кожна відповідь PostgREST, у тому числі анонімна.
--     Але поверхня привілеїв — це список, який читають люди, і кожен зайвий
--     рядок у ньому доводиться пояснювати. Клієнт-синхронізатор
--     (`components/ServerClockSync.tsx`) не робить виклику без сесії, тож
--     анонімні сторінки (login/register/set-password) нічого не втрачають:
--     вони й не показують клінічного часу.
--
--  ⚠️ ПОРЯДОК ВИКОТУ:
--     1) СПОЧАТКУ ця міграція. Стара збірка про функцію не знає — ВТРАТ НУЛЬ.
--     2) ПОТІМ деплой коду.
--     Зворотний порядок теж не ламає даних: `ServerClockSync` отримає 42883,
--     зсув лишиться 0, і поведінка буде РІВНО такою, як до пакета (браузерний
--     годинник). Тобто тут — на відміну від 0168 — безпечні обидва боки, і це
--     навмисно: фолбек нового коду є статус-кво, а не деградація.
-- ---------------------------------------------------------------------------

begin;

do $ledger$
begin
  if not exists (select 1 from public.migration_ledger
                 where name = '0168_emergency_stop_returns_incident_ids.sql') then
    raise exception '0169 потребує 0168 (накатуйте по порядку)';
  end if;
end
$ledger$;

-- stable, не volatile: у межах одного statement значення одне — саме та
-- семантика, що в `now()`. Кешування на рівні HTTP неможливе: supabase-js
-- кличе RPC методом POST.
--
-- ⚠️ `set search_path` тут — ОДНОРІДНІСТЬ, а не вимога безпеки, і це названо
--    чесно (ревʼю А): функція `security invoker`, тіло — `select now()`, а
--    `now()` резолвиться з pg_catalog, який неявно перший у шляху завжди.
--    Інваріант №2 `invariants_check` питає search_path лише в `security
--    definer` функцій, тож формально його можна було не ставити. Ставимо, щоб
--    у теці не з'явилось двох правил «коли прибивати шлях, а коли ні»; ціна —
--    функція не інлайниться планувальником, що тут не має значення (три
--    виклики на синхронізацію).
create or replace function public.server_now()
returns timestamptz
language sql
stable
security invoker
set search_path to 'public', 'pg_temp'
as $function$
  select now();
$function$;

/* Пастка 0122: без цих рядків EXECUTE має і PUBLIC, і anon.
   ACL визначається ПОВНІСТЮ, без опори на дефолт схеми: спершу знімаємо все з
   усіх клієнтських ролей, потім даємо рівно одній.
   ⚠️ `service_role` тут ВІДКЛИКАНО — і це відрізняється від 0168 навмисно.
   Там service_role грантувався явно, щоб ВІДНОВИТИ право, яке функція мала до
   міграції. У нової функції доміграційного ACL немає, відновлювати нічого, а
   серверного споживача не існує: серверний код зве `now()` прямо в SQL.
   Скопіювати форму 0168 без її підстави означало б розширити список, який
   читають люди, і не змогти пояснити навіщо. */
revoke all     on function public.server_now() from public, anon, authenticated, service_role;
grant  execute on function public.server_now() to authenticated;

/* ⚠️ АССЕРТ У ТІЙ САМІЙ ТРАНЗАКЦІЇ (канон 0168, знахідка ревʼю U-56 — MAJOR;
   у першій редакції 0169 його не було, і це знайшло ревʼю А цього пакета).
   Без нього міграція комітиться незалежно від того, яким ACL вийшов
   НАСПРАВДІ, а весь доказ живе у смоуку, який людина мусить не забути
   запустити окремою сесією. Для функції, що СТВОРЮЄТЬСЯ в схемі public,
   це найслабше місце: на іншому середовищі (staging, гілкова БД, відновлення
   з бекапу, self-hosted) набір default ACL інший, і перелік ролей у revoke
   міг не покрити фактичний дефолт. Тепер пастка фізично не переживає накат:
   транзакція відкотиться. */
do $acl$
declare
  v_fn constant regprocedure := 'public.server_now()'::regprocedure;
begin
  if (select proacl from pg_proc where oid = v_fn) is null then
    raise exception '0169: ACL порожній — діє ДЕФОЛТ, а він дає EXECUTE клієнтським ролям';
  end if;
  if has_function_privilege('anon', v_fn, 'EXECUTE') then
    raise exception '0169: anon дістав EXECUTE — пастка 0122 пережила revoke';
  end if;
  if exists (select 1 from pg_proc p, aclexplode(p.proacl) a
              where p.oid = v_fn and a.grantee = 0 and a.privilege_type = 'EXECUTE') then
    raise exception '0169: EXECUTE віддано PUBLIC — це ширше за anon';
  end if;
  if has_function_privilege('service_role', v_fn, 'EXECUTE') then
    raise exception '0169: service_role дістав EXECUTE — споживача немає, право зайве';
  end if;
  if not has_function_privilege('authenticated', v_fn, 'EXECUTE') then
    raise exception '0169: authenticated БЕЗ EXECUTE — вимірювач годинника мертвий';
  end if;
end
$acl$;

comment on function public.server_now() is
  '0169 (Ф4-8): віддає now() бази — джерело часу для вимірювання зсуву '
  'годинника браузера (lib/serverClock.ts). Авторитет той самий, що ставить '
  'in_progress_at і рахує вікна гардів. EXECUTE — рівно authenticated; anon, '
  'PUBLIC і service_role знято явно (пастка 0122), серверного споживача немає. '
  'Логіки не містить: RTT, вибір проби і поріг довіри — на клієнті.';

-- ============================================================================
-- Самореєстрація (канон 0142) — ОСТАННІЙ statement перед commit
-- ============================================================================
insert into public.migration_ledger (name)
values ('0169_server_now.sql')
on conflict (name) do nothing;

commit;

