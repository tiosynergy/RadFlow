-- ============================================================================
-- 0126_rooms_delete_history_guard.sql
-- Видалити кабінет можна ЛИШЕ якщо в ньому НІКОЛИ не було жодного запису.
--
-- ── ЩО СТАЛОСЬ ──────────────────────────────────────────────────────────────
-- `queue_entries.room_id` і `waitlist_entries.room_id` оголошені як
-- ON DELETE SET NULL (0001). Тому видалення кабінету не падає — воно МОВЧКИ
-- знеособлює всю його історію: записи лишаються в базі, але без кабінету.
-- У проді на 2026-07-28 таких сиріт назбиралось 44 (сесія 18 їх вичищає
-- скриптом supabase/maintenance/2026-07-28_cleanup_roomless_entries.sql).
-- Дірки в застосунку немає — у схемах запису в ЧЕРГУ `roomId: zUuid`
-- обовʼязковий; сироти зʼявились саме через DELETE кабінету. (Вейтліст свідомо
-- дозволяє `zUuid.nullish()`: бронь без кабінету — легальний стан «підберемо
-- апарат пізніше», а не сирота.)
--
-- Наслідки такої сироти видно всюди: у рядку черги кабінет порожній, на дошку
-- кабінету запис не потрапляє, у KPI його хвилини не належать жодному апарату
-- (для них у CeoDashboard і зʼявився рядок «+ N хв поза кабінетами», сесія 17).
-- Відновити звʼязок неможливо: у рядку більше немає жодного сліду, ЯКИЙ саме
-- кабінет там був.
--
-- ── ПРАВИЛО (рішення власника 2026-07-28) ───────────────────────────────────
-- Кабінет із БУДЬ-ЯКОЮ історією (хоч один рядок у черзі або вейтлісті, будь-який
-- статус, будь-яка дата, зокрема повністю закрита минула) НЕ ВИДАЛЯЄТЬСЯ ніколи.
-- Правильна дія для «апарат більше не працює» — ВИМКНУТИ його (0123): нових
-- записів він не приймає, з робочих екранів зникає (сесія 17), а прайс, історія
-- та привʼязки лишаються цілі.
--
-- Розглянутий і відкинутий мʼякший варіант — «блокувати лише поки є майбутні
-- активні записи» (правило, яке діяло з 2026-07-27 до цієї міграції). Воно
-- захищало живого пацієнта, але саме воно й породило 44 сироти: закрита минула
-- історія під нього не підпадала і зникала мовчки. Історія — теж дані центру.
--
-- Отже видалення лишається можливим рівно для одного випадку: кабінет завели
-- помилково і в ньому НІКОЛИ нікого не записували. Це і був єдиний легітимний
-- сценарій кнопки «✕».
--
-- ── ЩО РОБИТЬ МІГРАЦІЯ ──────────────────────────────────────────────────────
--   1) guard_delete_room() — одна функція на два правила, у явному порядку:
--      спершу «є історія» (заборона НАЗАВЖДИ), потім «ще ввімкнений» (тимчасова
--      вимога 0123). Порядок важливий для UX: інакше власник спершу вимикав би
--      кабінет, зберігав, повертався видаляти — і лише тоді дізнавався, що
--      видалити не можна взагалі;
--   2) trg_guard_delete_room замість trg_guard_delete_active_room; стара функція
--      guard_delete_active_room() прибирається (її правило переїхало цілком).
--
-- Чого міграція СВІДОМО не робить:
--   • НЕ міняє ON DELETE SET NULL на RESTRICT. Це виглядає прямішим рішенням,
--     але RESTRICT дав би сирий 23503 із текстом про constraint замість
--     зрозумілого повідомлення, зламав би каскадне видалення КЛІНІКИ (там
--     rooms йдуть каскадом, і записи мають зникати разом із центром) і не
--     покрив би вейтліст із його власною логікою. Тригер вирішує все троє.
--   • НЕ чіпає services / incidents / radiologist_rooms: їхній CASCADE лишається,
--     бо кабінет без історії тягне за собою лише власну конфігурацію.
--   • НЕ забороняє вимкнення. Вимкнути можна будь-коли й будь-який кабінет.
--
-- ⚠️ ПОРЯДОК ВИКАТКИ — СПЕРШУ БД, ПОТІМ КЛІЄНТ. Клієнт лише дублює правило
-- заздалегідь (щоб діалог пояснював людською мовою, а не тостом із кодом);
-- справжній рубіж — цей тригер. Старий клієнт проти нової БД теж безпечний:
-- він просто отримає ROOM_HAS_HISTORY у тост «Помилка збереження», а дані
-- лишаться цілі — саме те, чого ми й домагаємось.
--
-- Ідемпотентна: create or replace, drop trigger if exists + create,
-- drop function if exists. Застосовує власник вручну в Supabase SQL Editor.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- 0. Освіжаємо коментар колонки `rooms.active`
--
-- Він написаний у 0123 і посилається на функцію guard_delete_active_room, яку
-- ця сама міграція нижче дропає, і описує вже скасоване правило. `\d+ rooms` у
-- SQL Editor — канонічний спосіб звіритись із прод-схемою в цьому проєкті, тож
-- залишений як є коментар — це повторення інциденту «протухлий коментар збив
-- наступну сесію».
-- ---------------------------------------------------------------------------
comment on column public.rooms.active is
  'false = кабінет вимкнено: нові записи/переноси сюди заборонені (тригер '
  'check_room_active), наявні записи лишаються робочими. Видалити рядок можна '
  'лише якщо в кабінеті НІКОЛИ не було жодного запису (ні в queue_entries, ні в '
  'waitlist_entries) І лише при active=false — тригер guard_delete_room. 0123 + 0126.';

-- ---------------------------------------------------------------------------
-- 1. Гард видалення кабінету
--
-- pg_trigger_depth() = 1 → це ПРЯМЕ видалення кабінету. Каскад від видалення
-- клініки (rooms_clinic_id_fkey ON DELETE CASCADE) теж запускає рядкові тригери,
-- і без цієї умови «видалити центр» падало б повідомленням про історію кабінету,
-- яке в тому контексті безглузде (та сама причина, що в 0123, ревʼю Medium-1).
--
-- Рахуємо ІСНУВАННЯ, а не кількість: `exists` зупиняється на першому рядку.
-- Обидва запити йдуть по індексах (queue_room_date_idx — префікс room_id,
-- waitlist_room_idx — частковий по room_id is not null), тож гард лишається
-- дешевим навіть на великій історії.
--
-- Кількості для тексту помилки рахуємо ЛИШЕ коли вже вирішили падати: на
-- щасливому шляху (видаляють порожній кабінет) зайвих count(*) немає.
-- ---------------------------------------------------------------------------
create or replace function public.guard_delete_room()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_queue bigint;
  v_wl    bigint;
begin
  if pg_trigger_depth() > 1 then
    return old;  -- каскад від видалення клініки: кабінет має зникнути разом із центром
  end if;

  if exists (select 1 from public.queue_entries q where q.room_id = old.id)
     or exists (select 1 from public.waitlist_entries w where w.room_id = old.id)
  then
    select count(*) into v_queue from public.queue_entries q where q.room_id = old.id;
    select count(*) into v_wl    from public.waitlist_entries w where w.room_id = old.id;

    /* Текст із числами — навмисно. На відміну від 0123 §2 (де повідомлення
       могло стати оракулом чужої назви кабінету), сюди можна дійти лише маючи
       право DELETE на цей рядок, тобто будучи адміном ЦІЄЇ клініки: нічого,
       чого власник ще не знає, повідомлення не розкриває. */
    raise exception
      'ROOM_HAS_HISTORY: у кабінеті «%» є історія (записів: %, броней вейтліста: %) — видалити не можна. Вимкніть кабінет: історія лишиться цілою, а нових записів він не прийматиме.',
      old.name, v_queue, v_wl
      using errcode = 'check_violation';
  end if;

  /* Історії немає → лишається правило 0123: видаляти можна лише вимкнений.
     Двокроковість тут уже майже формальність (видаляти нема чого, крім
     конфігурації), але вона й далі рятує від видалення кліком по «✕» у
     кабінеті, який щойно завели й ось-ось почнуть використовувати. */
  if old.active then
    raise exception 'ROOM_ACTIVE_DELETE: спершу вимкніть кабінет «%», потім видаляйте', old.name
      using errcode = 'check_violation';
  end if;

  return old;
end;
$function$;

comment on function public.guard_delete_room() is
  'BEFORE DELETE ON rooms: заборонити видалення кабінету, у якому є БУДЬ-ЯКА '
  'історія (queue_entries / waitlist_entries, будь-який статус і дата) — інакше '
  'ON DELETE SET NULL мовчки знеособив би записи. Кабінет без історії видаляється '
  'лише вимкненим (правило 0123). Каскад від видалення клініки пропускається. 0126.';

-- ---------------------------------------------------------------------------
-- 2. Тригер. Алфавіт: trg_guard_delete_room < trg_prune_referral_rooms
-- (AFTER DELETE), тож прибирання room_ids у направників відпрацює вже після
-- дозволу на видалення — як і було з trg_guard_delete_active_room.
-- ---------------------------------------------------------------------------
drop trigger if exists trg_guard_delete_active_room on public.rooms;
drop trigger if exists trg_guard_delete_room on public.rooms;
create trigger trg_guard_delete_room
  before delete on public.rooms
  for each row execute function public.guard_delete_room();

-- Стара функція більше не викликається нізвідки: її правило цілком усередині
-- guard_delete_room(). Прибираємо, щоб наступна сесія не читала два гарди й не
-- гадала, який із них чинний.
drop function if exists public.guard_delete_active_room();

-- ---------------------------------------------------------------------------
-- 3. ACL
--
-- ⚠️ Пастка Supabase: у схемі public діє `alter default privileges … grant
-- execute on functions to anon, authenticated, service_role`, тож ЩОЙНО
-- СТВОРЕНА функція автоматично отримує execute для anon, і `revoke … from
-- public` цього НЕ знімає. Тригерну функцію поза тригером усе одно не
-- викликати (0A000), але зайвий грант анонімові не лишаємо — правило єдине
-- для всіх нових функцій проєкту.
-- ---------------------------------------------------------------------------
revoke all on function public.guard_delete_room() from public;
revoke execute on function public.guard_delete_room() from anon;

commit;
