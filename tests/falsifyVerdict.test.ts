/* ===== U-74. Сторож НАД сторожами: вердикт стенда фальсифікації =====

   Стенди фальсифікації — інструмент, яким у цьому проєкті перевіряють усе
   інше. До с51 вони не мали коду повернення: мутація, яка НЕ ВІДБУЛАСЬ
   (протухлий якір після рефактора), давала рядок «⛔ відхилено» в таблиці — і
   прогін завершувався нулем. У с50 так мовчки протухли три якорі в
   falsify-f4-2, у с51 живий прогін знайшов ПʼЯТЬ у falsify-u70, серед них
   сторож рівно на ту помилку, заради якої стенд писався.

   ⚠️ Перевіряється ВИКЛИКОМ, а не піном по джерелу: цей модуль сам розбирає
   текст, тож пін по тексту був би тавтологією («формула повторює формулу»).
   Кожен кейс нижче — окремий ВХІД, а не повтор виклику. */

import { describe, it, expect } from "vitest";
/* Модуль стендів — .mjs; типи він віддає через JSDoc, і `tsc --noEmit` їх
   читає. Саме тому `counts` там типізований поіменно, а не як `object`. */
import { verdictOf } from "../scripts/lib/falsify-verdict.mjs";

const HEAD = [
  "| # | мутація | очікування | спек-сторож | факт | вердикт |",
  "|---|---|---|---|---|---|",
];
const row = (id: string, verdict: string) =>
  `| ${id} | якась мутація | ЧЕРВОНЕ | serverClock.test.ts | «спек» | ${verdict} |`;

describe("вердикт стенда фальсифікації (U-74)", () => {
  it("усі мутації відпрацювали → стенд зелений", () => {
    const v = verdictOf([...HEAD, row("M1", "✅"), row("M2", "✅")], 2);
    expect(v.ok).toBe(true);
    expect(v.counts.passed).toBe(2);
    expect(v.summary).toContain("ЗЕЛЕНИЙ");
  });

  /* ГОЛОВНИЙ КЕЙС ПАКЕТА: саме він до с51 давав нуль і читався як успіх. */
  it("протухлий якір валить прогін, навіть коли решта зелена", () => {
    const v = verdictOf([...HEAD, row("M1", "✅"), row("M2", "⛔ відхилено")], 2);
    expect(v.ok).toBe(false);
    expect(v.counts.rejected).toBe(1);
    expect(v.summary).toContain("відхилених якорів");
  });

  it("сторож, що не тримає, валить прогін", () => {
    const v = verdictOf([...HEAD, row("M1", "⛔ СТОРОЖ НЕ ТРИМАЄ")], 1);
    expect(v.ok).toBe(false);
    expect(v.counts.notHeld).toBe(1);
  });

  it("мутація, що зламала збірку, валить прогін", () => {
    const v = verdictOf([...HEAD, row("M1", "⛔ мутація зламала збірку")], 1);
    expect(v.ok).toBe(false);
    expect(v.counts.crashed).toBe(1);
  });

  it("спіймав ЧУЖИЙ спек — теж не «зелено»", () => {
    const v = verdictOf([...HEAD, row("M1", "⚠️ спіймав ЧУЖИЙ спек, не названий сторож")], 1);
    expect(v.ok).toBe(false);
    expect(v.counts.wrongSpec).toBe(1);
  });

  /* Розбір власного виводу сліпий до рядка, якого НЕМА, — тому окремо
     звіряється кількість. Мутація «викинути push у гілці» ловиться саме тут. */
  it("мутація без рядка в таблиці валить прогін", () => {
    const v = verdictOf([...HEAD, row("M1", "✅")], 3);
    expect(v.ok).toBe(false);
    expect(v.summary).toContain("не дали рядка");
  });

  it("рядків більше, ніж мутацій — розбір збився, теж червоно", () => {
    const v = verdictOf([...HEAD, row("M1", "✅"), row("M2", "✅")], 1);
    expect(v.ok).toBe(false);
    expect(v.summary).toContain("більше, ніж мутацій");
  });

  /* ⚠️ Знахідка ревʼю А: у першій редакції `expected` не-число ТИХО вимикало
     звірку кількості — сторож наполовину замовкав і рапортував зеленим. */
  it("expected не-число — падаємо голосно, а не мовчки вимикаємо звірку", () => {
    // @ts-expect-error — навмисно невірний виклик: це і є перевіряний вхід
    expect(() => verdictOf([...HEAD, row("M1", "✅")])).toThrow(/expected/);
    // @ts-expect-error — те саме для рядка
    expect(() => verdictOf([...HEAD, row("M1", "✅")], "1")).toThrow(/expected/);
  });

  it("невпізнаний вердикт не рахується за успіх", () => {
    const v = verdictOf([...HEAD, row("M1", "нове слово")], 1);
    expect(v.ok).toBe(false);
    expect(v.counts.unknown).toBe(1);
    expect(v.counts.passed).toBe(0);
  });

  it("червона базова лінія валить прогін навіть без жодного рядка", () => {
    const v = verdictOf(["⛔ Базова лінія червона — стенд НІЧОГО не доводить. Червоні: X"], 0);
    expect(v.ok).toBe(false);
    expect(v.summary).toContain("базова лінія");
  });

  /* Шапка і роздільник не мусять рахуватись за мутації: інакше лічильник
     розійдеться з MUTATIONS.length на кожному стенді і всі стануть червоні. */
  it("шапка і роздільник не рахуються", () => {
    const v = verdictOf([...HEAD, row("M1", "✅")], 1);
    expect(v.ok).toBe(true);
    expect(v.counts.unknown).toBe(0);
  });

  /* Стенди з ІНШОЮ шириною таблиці (у falsify-u61 п'ять колонок, а не шість)
     мусять розбиратись тим самим модулем — вердикт живе в ОСТАННІЙ клітинці. */
  it("таблиця іншої ширини розбирається так само", () => {
    const v = verdictOf([
      "| # | мутація | очікування | факт | вердикт |",
      "|---|---|---|---|---|",
      "| M1 | якась мутація | ЧЕРВОНЕ | «спек» | ✅ |",
      "| M2 | якась мутація | ЧЕРВОНЕ | ЯКІР НЕ УНІКАЛЬНИЙ (0) | ⛔ відхилено |",
    ], 2);
    expect(v.ok).toBe(false);
    expect(v.counts.passed).toBe(1);
    expect(v.counts.rejected).toBe(1);
  });

  /* Преамбула стенда (заголовок, рядок базової лінії) не є таблицею. */
  it("преамбула не плутається з рядками таблиці", () => {
    const v = verdictOf([
      "# Стенд фальсифікації X",
      "**БАЗОВА ЛІНІЯ:** ЗЕЛЕНА (165 тестів у 4 спеках)",
      "",
      ...HEAD,
      row("M1", "✅"),
    ], 1);
    expect(v.ok).toBe(true);
  });
});
