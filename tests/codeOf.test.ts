// Межі codeOf() — щоб наступний не прийняв його за токенізатор.
//
// codeOf прибирає коментарі перед статичним сторожем. Він регулярковий і про
// рядкові літерали не знає, тож помилятися може В ОБИДВА боки:
//   • гола "//" всередині літерала зріже РЕШТУ рядка → сторож ложно-ЧЕРВОНИЙ;
//   • "/" + "*" усередині літерала зʼїсть усе до наступного закриття → сторож
//     ложно-ЗЕЛЕНИЙ, бо проковтнутий код він уже не побачить.
// Обидва випадки запиновані нижче: не як «правильна поведінка», а як ВІДОМА
// межа. Прийде третій сторож, якому цього замало, — тут і буде видно, що саме
// доведеться міняти (і що при цьому зламається).
//
// Ревʼю с46 р2, F9.
import { describe, it, expect } from "vitest";
import { codeOf } from "./helpers/codeOf";

const SLASH = "/";
const STAR = "*";
const OPEN = SLASH + STAR;    // початок блочного коментаря, зібраний по частинах,
const CLOSE = STAR + SLASH;   // щоб не закривати коментар цього ж файлу

describe("codeOf — що саме він робить", () => {
  it("прибирає блочний коментар", () => {
    const src = `const a = 1; ${OPEN} const b = 2; ${CLOSE} const c = 3;`;
    expect(codeOf(src)).toContain("const a");
    expect(codeOf(src)).toContain("const c");
    expect(codeOf(src)).not.toContain("const b");
  });

  it("прибирає рядковий коментар до кінця рядка", () => {
    const src = ["const a = 1;", SLASH + SLASH + " const b = 2;", "const c = 3;"].join("\n");
    expect(codeOf(src)).not.toContain("const b");
    expect(codeOf(src)).toContain("const c");
  });

  it("НЕ чіпає http:// у літералі (захист по двокрапці)", () => {
    const src = `const u = "https:${SLASH}${SLASH}example.test"; const keep = 1;`;
    expect(codeOf(src)).toContain("example.test");
    expect(codeOf(src)).toContain("keep");
  });

  /* ВІДОМА МЕЖА №1: гола пара слешів у літералі зріже решту рядка.
     Наслідок для сторожа: якір, що стоїть ПРАВІШЕ такого літерала на тому ж
     рядку, зникне — тест почервоніє на здоровому коді. */
  it("МЕЖА: гола пара слешів у літералі зʼїдає решту рядка", () => {
    const src = `const p = "${SLASH}${SLASH}cdn.test"; const anchor = 1;`;
    expect(codeOf(src)).not.toContain("anchor");
  });

  /* ВІДОМА МЕЖА №2: відкриття блоку в літералі ковтає код до першого закриття.
     Наслідок гірший: сторож, який шукає ДРУГЕ входження або «найближчий гейт»,
     проковтнутого коду не побачить і лишиться зеленим. */
  it("МЕЖА: відкриття блоку в літералі ковтає код до наступного закриття", () => {
    const src = `const p = "${OPEN}"; const swallowed = 1; const q = "${CLOSE}"; const after = 2;`;
    expect(codeOf(src)).not.toContain("swallowed");
    expect(codeOf(src)).toContain("after");
  });

  /* Захист по двокрапці (щоб не різати https://) має і зворотний бік: пара
     слешів ОДРАЗУ після двокрапки не вважається коментарем. Пінуємо саме це —
     тест «рядок не мутується» був тавтологією (примітив незмінний), тобто
     сторожем не був узагалі (ревʼю с46 р3, F6). */
  it("МЕЖА: коментар одразу після двокрапки НЕ вирізається", () => {
    // Перед парою слешів стоїть саме двокрапка — той самий захист, що рятує https://.
    const src = `const o = { k:${SLASH}${SLASH} нотатка`;
    expect(codeOf(src)).toContain("нотатка");
  });
});
