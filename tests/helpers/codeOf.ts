// Спільний хелпер статичних сторожів: прибрати коментарі, лишити КОД.
//
// Навіщо: сторож, який шукає рядок у файлі компонента, інакше знаходить його в
// ПОЯСНЕННІ поруч із правкою — і лишається зеленим після того, як сам код
// видалили. У пакеті с46 так і сталося б: коментар над блоком підтвердження
// дослівно цитує «✓ Слот вільний».
//
// Файл навмисно БЕЗ ".test." у назві: vitest збирає лише файли з ".test.ts"
// (див. include у vitest.config.ts), тож хелпер не поїде як порожній сьют.
//
// ⚠️ Це НЕ токенізатор: він не знає про рядкові літерали. Межі поведінки
// зафіксовані в tests/codeOf.test.ts — читай їх, перш ніж покластися на нього
// в новому сторожі.
//
// Беклог P3: копії цієї ж заміни лежали в referrerField.test.ts і
// setupWizard.test.ts — обидві переведені сюди в с46.
export const codeOf = (src: string) =>
  src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/.*$/gm, "$1");
