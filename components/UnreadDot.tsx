"use client";

/* ===== RadFlow — контекстна позначка непрочитаної зміни («червона крапка») =====
   ТЗ: CLAUDE_CONTEXTUAL_UNREAD_CHANGES_PROMPT.md.

   ⚠️ Стан НЕ передається лише кольором (WCAG 1.4.1 + правило проєкту «статус —
   глифом І кольором»): крапка завжди несе приховане текстове імʼя, яке каже,
   ЩО саме змінилось і ХТО змінив. Сама наявність крапки — теж неколірний
   сигнал (форма зʼявилась / зникла).

   ⚠️ Глобального дзвіночка, інбоксу й нижнього індикатора в системі немає за
   вимогою ТЗ. Ця крапка живе ТІЛЬКИ поруч із конкретною інформацією. */

import type { ChangeMarker } from "@/lib/unreadChanges";
import { topSeverity, unreadGroupLabel, unreadNavLabel } from "@/lib/unreadChanges";

type Props = {
  /** Позначки, що стоять за цією крапкою (порожньо → нічого не малюємо). */
  markers: readonly ChangeMarker[];
  /** Показувати ЧИСЛО (пункти навігації, шапки секцій) — завжди, навіть «1».
   *  ⚠️ До с48 число зʼявлялось лише від ДВОХ позначок, а одна давала німу
   *  крапку. Саме на ній власник і спіткнувся: «подія, позначена червоною
   *  крапкою, не розпізнана». Найчастіший стан (одна зміна) був найменш
   *  зрозумілим — див. коментар до рендера нижче. */
  withCount?: boolean;
  /** Оголошувати появу асистивним технологіям. Вмикати ТОЧКОВО — на екрані
   *  не повинно бути десятка живих областей, що говорять одночасно. */
  live?: boolean;
  className?: string;
};

export default function UnreadDot({ markers, withCount = false, live = false, className }: Props) {
  if (!markers.length) return null;

  const sev = topSeverity(markers) ?? "info";
  /* ⚠️ Підпис залежить від того, чи видно цифру. Коли цифра видна, текст мусить
     починатися з неї («Є непрочитані зміни: N»), інакше бейдж «1» читається як
     лічильник СУТНОСТЕЙ — так само, як сусідній «Лист очікування 1». */
  const label = withCount ? unreadNavLabel(markers) : unreadGroupLabel(markers);
  const cls =
    "rf-dot rf-dot-" + sev + (withCount ? " rf-dot-num" : "") +
    (className ? " " + className : "");

  return (
    <span
      className={cls}
      /* ⚠️ U-30 (с48): до цього розшифровка існувала ТІЛЬКИ в `.rf-vh`, тобто
         лише для скрінрідера: формально WCAG 1.4.1 виконано, а зряча людина
         отримувала голу кольорову крапку без жодного пояснення. Дзеркальна
         позначка на MiniCalendar title мала з самого початку — дві крапки
         однієї родини поводились по-різному. Тепер однаково.

         ⚠️ Але title — це МИША. З клавіатури й з пальця його не видно, тож на
         дотикових екранах пояснення несе саме ЧИСЛО (рішення власника, с48:
         «число вирішує, тултип — бонус»). Писати тут «title — єдине, що бачить
         зряча людина» було б неправдою для половини пристроїв; ревʼю це
         зловило. Повноцінна підказка для дотику — окремим пунктом (U-31). */
      title={label}
      /* role="status" (ввічливий) — а не alert: зміна даних не є аварією і не
         повинна переривати те, що користувач зараз читає. */
      {...(live ? { role: "status" as const } : {})}
    >
      {/* ⚠️ Число показуємо ЗАВЖДИ при withCount, включно з «1». Стара умова
          `markers.length > 1` робила найчастіший стан найменш зрозумілим:
          одна зміна — і замість бейджа німа крапка 8×8. Рішення власника
          (с48): «якщо є число — показувати завжди». */}
      <span aria-hidden="true">{withCount ? markers.length : "●"}</span>
      <span className="rf-vh">{label}</span>
    </span>
  );
}
