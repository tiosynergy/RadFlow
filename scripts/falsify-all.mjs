// ============================================================
//  U-74. ОДИН ПРОГІН УСІХ СТЕНДІВ ФАЛЬСИФІКАЦІЇ — з підсумковим вердиктом.
//
//  ЧОМУ ЦЕ ІСНУЄ. Стендів у проєкті двадцять, вони писались у різні сесії і
//  живуть кожен своїм життям. Поки жоден із них не мав коду повернення,
//  протухлий після рефактора якір ніхто не бачив роками: у с50 три таких
//  знайшлись у falsify-f4-2, у с51 — пʼять у falsify-u70, і серед них сторож
//  рівно на ту помилку, заради якої стенд писався.
//
//  ⚠️ Стенди правлять БОЙОВІ файли, тож ганяються СТРОГО ПО ЧЕРЗІ. Паралельний
//     запуск двох стендів затер би відновлення один одного.
//  ⚠️ Прогін довгий (десятки хвилин): це не частина гейта, а окрема ревізія
//     інструментів. Запускати після рефакторів, які рухали код під якорями.
//
//  Запуск:  node scripts/falsify-all.mjs                 (усі; дерево має бути чистим)
//           node scripts/falsify-all.mjs u70 u72         (лише названі)
//           node scripts/falsify-all.mjs --allow-dirty   (є незакомічені правки)
//  Код повернення: 1, якщо хоч один стенд червоний; 2 — ревізія не почалась.
// ============================================================
import { readdirSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";

const DIR = "scripts";
const OUT = "falsify-all.md";
const argv = process.argv.slice(2);
/* Ревізію інструментів доводиться ганяти і ДО коміту пакета — інакше замок:
   комітити нема чого, поки стенди не зелені, а стенди не ганяються, поки не
   закомічено. Прапорець дозволяє старт із брудним деревом, але НЕ послаблює
   перевірку між стендами (звіряється вміст, а не набір шляхів) і друкує в
   звіті, що ревізія міряла НЕ закомічений код. */
const ALLOW_DIRTY = argv.includes("--allow-dirty");
const only = argv.filter((a) => !a.startsWith("--"));

/* ⚠️ Пін на КІЛЬКІСТЬ стендів (знахідка ревʼю А). Без нього перейменований,
   перенесений у підпапку або випадково видалений стенд просто зникає з
   вибірки, і ревізія друкує «усі 19 стендів зелені» — той самий мовчазний
   розхід, проти якого написана вся ця машинерія. Одна константа, а не
   двадцять: аргумент «магічні числа розійдуться» тут не працює. */
const EXPECTED_STANDS = 21;   // с54: +falsify-g1f (Г1-F, довіра до годинника клієнта)

const all = readdirSync(DIR)
  .filter((f) => /^falsify-.*\.mjs$/.test(f) && f !== "falsify-all.mjs")
  .sort();
const files = only.length ? all.filter((f) => only.some((o) => f.includes(o))) : all;
const countMismatch = !only.length && all.length !== EXPECTED_STANDS;

if (!files.length) {
  console.error(`Жоден стенд не підійшов під фільтр: ${only.join(", ")}`);
  process.exit(2);
}

const rows = [];
let failed = 0;
const t0 = Date.now();

/** Змінені ВІДСТЕЖУВАНІ файли (нові файли не рахуємо — вони нікого не труять). */
const dirtyTracked = () =>
  (spawnSync("git", ["status", "--porcelain"], { encoding: "utf8" }).stdout || "")
    .split("\n").map((s) => s.trim()).filter(Boolean).filter((l) => !/^\?\?/.test(l));

/* ⚠️ Звіряється ВМІСТ, а не набір шляхів. Перша редакція цієї перевірки
   порівнювала список із `git status --porcelain` — і була сліпа рівно там, де
   найнебезпечніше: якщо стенд мутував файл, який і без нього стояв « M »
   (незакомічена правка інструментів у тій самій сесії), рядок статусу не
   змінювався, і отруєне дерево читалось як відновлене. `git diff HEAD` бачить
   самі байти, тож підміна всередині вже брудного файлу дає інший хеш. */
const diffChunks = () => {
  const r = spawnSync("git", ["diff", "HEAD"],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
  if (r.status !== 0 || typeof r.stdout !== "string") {
    console.error("⛔ `git diff HEAD` не відпрацював — звірити дерево нічим, ревізія без цього не має сенсу.");
    console.error(r.stderr || "");
    process.exit(2);
  }
  /* Ріжемо на шматки по файлах, щоб потім НАЗВАТИ отруєний файл, а не вивалити
     весь список брудних. У прогоні на брудному дереві список «після» збігається
     зі списком «до» поіменно (перевірено зондом), тож без цього різання звіт
     показував би сім рядків і жодного винуватця. */
  const m = new Map();
  for (const part of r.stdout.split(/^diff --git /m)) {
    if (!part.trim()) continue;
    const path = (part.match(/^a\/(\S+) b\//) || [])[1] || part.slice(0, 60);
    m.set(path, createHash("sha256").update(part).digest("hex"));
  }
  return m;
};

/** Файли, чий вміст розійшовся з точкою відліку (в обидва боки). */
const driftedFrom = (base) => {
  const now = diffChunks();
  const out = [];
  for (const [p, h] of now) if (base.get(p) !== h) out.push(base.has(p) ? `змінено ${p}` : `зʼявився ${p}`);
  for (const p of base.keys()) if (!now.has(p)) out.push(`зник ${p}`);
  return out;
};

/* ⚠️ ЧИСТОТА ДЕРЕВА ПЕРЕВІРЯЄТЬСЯ ПЕРЕД КОЖНИМ СТЕНДОМ, а не лише в кінці
   (с51). Коментар нижче правильно називав небезпеку — «зависла ітерація лишила
   б мутований файл, а наступний стенд прочитав би його як оригінал» — але
   ПЕРЕВІРКИ на неї не було: дерево звірялось один раз, після всього прогону.
   Тобто найгірший режим («один стенд помер, решта міряла отруєний код і
   рапортувала зелене») ревізія знаходила ПІСЛЯ того, як надрукувала свої
   зелені рядки, і не знала, які саме з них недійсні.
   Це не теорія: у с51 стенд `falsify-u15` помер із кодом 7 (обробник винятків
   Node сам кинув) і лишив `components/StudyEditModal.tsx` мутованим — а
   наступні стенди спокійно показали ✅ на отруєному файлі.
   Тепер прогін зупиняється на першому ж брудному дереві і НАЗИВАЄ винуватця. */
const dirtyBefore = dirtyTracked();
if (dirtyBefore.length && !ALLOW_DIRTY) {
  console.error("⛔ Дерево брудне ДО ревізії — стенди міряли б не той код:");
  for (const l of dirtyBefore) console.error(`   ${l}`);
  console.error("Закомітьте або відкотіть правки і запустіть знову.\n" +
    "Якщо це ваші правки в роботі і ви щойно на них дивились — `--allow-dirty`:\n" +
    "ревізія стартує, перевірка між стендами лишається, а звіт скаже, що код НЕ закомічений.");
  process.exit(2);
}
if (dirtyBefore.length) {
  console.error("⚠️ РЕВІЗІЯ НА БРУДНОМУ ДЕРЕВІ (--allow-dirty). Зелений результат нижче стосується\n" +
    "   НЕ закоміченого коду. Ці файли відрізняються від HEAD ще до першого стенда:");
  for (const l of dirtyBefore) console.error(`   ${l}`);
  console.error("");
}
/* Точка відліку: усе, чим дерево відрізняється від HEAD ЗАРАЗ. Далі кожен
   стенд мусить лишити його рівно таким. */
const baseline = diffChunks();

let poisonedBy = null;
for (const f of files) {
  const started = Date.now();
  process.stdout.write(`▶ ${f} … `);
  /* ⚠️ Таймаут обовʼязковий: стенд правит БОЙОВІ файли і відновлює їх у
     `finally`. Зависла в vitest ітерація лишила б мутований файл у дереві, а
     наступний стенд прочитав би його як «оригінал» і запік би мутацію.
     ⚠️ 45 хв, І ЦЕ ВИМІРЯНО ДВІЧІ (с53), а не взято про запас. Спершу стояло
     15 хв: `falsify-u72` виріс до 149 мутацій, узяв 901 с — на секунду більше
     за бюджет — і був убитий. Убитий таймаутом процес свого `finally` НЕ
     виконує, тож у дереві лишився мутований `WaitlistModal.tsx`, а ревізія
     стала на 20-му стенді з 20. Підняв до 25 хв — і ТОЙ САМИЙ стенд узяв
     1501 с, тобто вперся рівно в новий бюджет.
     ⚠️ І ОСЬ ГОЛОВНЕ, ЩО ПОКАЗАВ ДРУГИЙ ПРОГІН: справа не в стенді. Та сама
     ревізія на тому самому коді дала 836 с там, де три години тому було 238
     (`falsify-0166`), 996 проти 361 (`f4-portal`), 788 проти 224 (`u13`) —
     машина стала вдвічі-вчетверо повільнішою, і два стенди почервоніли ПОРОЖНІМИ
     фактами (вердикт є, таблиці немає), тобто не встигли. Бюджет мусить
     покривати НАЙГІРШУ машину, а не найкращу: ціна завищення — тільки довше
     чекання зависання, ціна заниження — весь прогін і отруєне дерево.
     ⚠️ Число ЗАЛЕЖНЕ від найдовшого стенда і від навантаження. Орієнтир:
     u72 = 149 мутацій, ~4 с/мутація на вільній машині і ~10 с на зайнятій. */
  const r = spawnSync("node", [`${DIR}/${f}`],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, timeout: 45 * 60_000 });
  const sec = Math.round((Date.now() - started) / 1000);
  const out = `${r.stdout || ""}\n${r.stderr || ""}`;
  /* Код повернення — головний сигнал. Але стенд міг і впасти до вердикту
     (не знайшов файл, зламався парсер): це теж червоне, і його треба
     відрізняти від «мутації не тримають». */
  const crashed = r.status === null || r.status > 1;
  const anchors = (out.match(/ЯКІР НЕ (УНІКАЛЬНИЙ|ЗНАЙДЕНО)/g) || []).length;
  /* Формулювання «сторож не спрацював» у стендів різні — три покоління писались
     у різні сесії. Ловимо всі відомі; невідома дасть 0 у колонці, але код
     повернення стенда все одно вирішальний. */
  const notHeld = (out.match(/НЕ ТРИМАЄ|дивиться не туди|ЧЕРВОНИЙ НЕ ТОЙ|ЧУЖИЙ спек/g) || []).length;
  /* ⚠️ U-80 ввів ЩЕ ТРИ формулювання, і без них запасний сторож був сліпий саме
     до них (знахідка ревʼю U-80): прогін, що складався б із самих «мутація
     зламала збірку», при знятому `process.exitCode` дав би тут ✅. */
  const noRun = (out.match(/зламала збірку|звіт не прочитано|прогін НЕ ВІДБУВСЯ|набір ЧЕРВОНИЙ ще до мутацій/g) || []).length;
  /* ⚠️ ПІДСУМКОВИЙ ВИРОК СТЕНДА — головний рядок його виводу, і саме його тут
     НЕ БУЛО (с52). Три набори вище збирались із пригод окремих сесій і знають
     по кілька фраз із трьох стендів; над ними стояв мій коментар, що режим
     «хтось зняв `process.exitCode`» уже закритий. Я цього не перевіряв. Коли
     перевірив — вивід усіх двадцяти стендів проти цих регексів, — виявилось,
     що ЖОДЕН із них не ловиться за текстом свого вироку: родина на спільній
     бібліотеці друкує `**ВЕРДИКТ: ⛔ СТЕНД ЧЕРВОНИЙ**`, рукописна —
     `⛔ ВЕРДИКТ: СТЕНД ЧЕРВОНИЙ`, і ні того, ні того в наборах немає. Тобто
     запасний сторож стеріг три випадкові фрази, а не вирок.
     Ловимо обидві форми плюс ті вироки, що друкуються ДО таблиці і скасовують
     увесь прогін (червона база, брехливий інвентар, звіту немає). */
  const verdictRed = (out.match(/ВЕРДИКТ: ⛔ СТЕНД ЧЕРВОНИЙ|⛔ ВЕРДИКТ: СТЕНД ЧЕРВОНИЙ|Базова лінія (?:червона|не зелена)|ПОМИЛКА: звіту немає|ІНВЕНТАР БРЕШЕ|Мутації НЕ ганялись|вимір не відбувся|ЧЕРВОНИЙ, а мав лишитись зеленим/g) || []).length;
  /* ⚠️ СКІЛЬКИ АДРЕСНИХ МУТАЦІЙ СТЕНД РЕАЛЬНО ПРОГНАВ. Без цього числа
     «двадцять мутацій утримались» і «мутацій не було жодної» дають однаковий
     зелений рядок: `verdictOf(lines, 0)` вважає 0/0 нормою, а рукописний стенд
     із порожнім `M` друкує `## ПІДСУМОК: 0/0 адресних` і виходить нулем.
     Окремо це закриває заморозку як спосіб тихо все погасити: задокументована
     процедура для протухлого якоря — дописати позицію в `FROZEN_STALE`, і ніщо
     не заважало дійти до 32 із 32. Заморожені позиції в це число не входять,
     тож стенд, у якому не лишилось жодної адресної, тепер ЧЕРВОНИЙ.
     Обидві родини друкують підсумок машинно-читано — інших форм у папці немає
     (звірено по всіх двадцяти). */
  const am = out.match(/ПІДСУМОК:\s*(\d+)\/(\d+)\s+адресних/)
          || out.match(/(\d+)\/(\d+)\s+мутацій відпрацювали/);
  const addressed = am ? { done: +am[1], total: +am[2] } : null;
  /* ⚠️ Улики рахуються В ВЕРДИКТ, а не лише друкуються (знахідка ревʼю Б).
     Інакше стенд, у якого хтось зняв `process.exitCode`, дав би рядок
     «✅ 0 | 9 протухлих якорів» і зелений підсумок — режим відмови, який цей
     пакет оголошує закритим. */
  /* ⚠️ ЗАМОРОЖЕНІ ПОЗИЦІЇ (с51). Стенд — це запис про СВІЙ коміт, і частина з
     них після мержу свого пакета більше не сторожить нічого: код, у який вони
     цілились, знято разом із дефектом. `falsify-u17-u18` це прямо оголошує в
     шапці. Досі ревізія про таке не знала і рахувала девʼять таких позицій за
     дефекти — тобто була ЗАВЖДИ червона з причини, яка дефектом не є. А
     ревізія, червона завжди, читається так само, як зелена завжди: ніяк.
     Тепер стенд може оголосити позицію замороженою, і ревізія показує це
     ОКРЕМОЮ колонкою — не як успіх і не як провал, а як те, чим воно є. Сам
     стенд при цьому звіряє свій інвентар заморозки з дійсністю в обидва боки,
     тож заморозка не місце, де ховають нове гниття. */
  const frozen = (out.match(/⏸ ЗАМОРОЖЕНО/g) || []).length;
  const loudRed = r.status !== 0 || anchors > 0 || notHeld > 0 || noRun > 0 || verdictRed > 0;
  /* Порожня робота — теж червоне, і саме її найважче помітити очима: стенд
     нічого не зламав, ні на що не поскаржився і вийшов нулем. Питання не «чи
     впав», а «чи щось довів». Перевіряємо лише коли інших уликів немає: у
     червоного стенда підсумок має іншу форму, і його відсутність там нормальна. */
  const emptyRun = !loudRed && (addressed === null || addressed.total === 0 || addressed.done === 0);
  const red = loudRed || emptyRun;
  if (red) failed++;
  rows.push({ f, sec, status: r.status, crashed, red, anchors, notHeld, noRun, verdictRed, frozen, addressed, emptyRun });
  console.log(red
    ? `⛔ (код ${r.status}${crashed ? ", впав до вердикту" : ""}${emptyRun ? ", ЖОДНОЇ адресної мутації" : ""}, ${sec} с)`
    : `✅ (${addressed.done}/${addressed.total} адресних${frozen ? `, ${frozen} заморожено` : ""}, ${sec} с)`);

  /* Стенд відпрацював — дерево мусить бути БАЙТ У БАЙТ таким, як до нього. */
  const left = driftedFrom(baseline);
  if (left.length) {
    poisonedBy = { f, left };
    console.error(`\n⛔ ${f} НЕ ВІДНОВИВ бойові файли — далі міряти нічого:`);
    for (const l of left) console.error(`   ${l}`);
    /* ⚠️ ВІДНОВЛЮЄМО ДЕРЕВО САМІ (с53). Ревізія не стартує на брудному дереві,
       тож усе, що розійшлось ПІСЛЯ точки відліку, — це залишена стендом
       мутація і нічия більше робота. Лишати її означало блокувати наступний
       запуск і, гірше, лишати в дереві правку, яку ніхто свідомо не робив: у
       с51 так помер `falsify-u15`, у с53 — `falsify-u72` по таймауту.
       Прогін від цього ЧЕРВОНИМ бути не перестає — саме тому відновлення
       стоїть ПІСЛЯ повідомлення, а не замість нього. */
    const restored = [];
    for (const l of left) {
      const p = l.replace(/^(змінено|зʼявився|зник) /, "");
      const g = spawnSync("git", ["checkout", "--", p], { encoding: "utf8" });
      restored.push(`${g.status === 0 ? "↩" : "✗"} ${p}`);
    }
    poisonedBy.restored = restored;
    console.error("Дерево відновлено автоматично (`git checkout --`):");
    for (const l of restored) console.error(`   ${l}`);
    console.error("Ревізія все одно зупинена: наступні стенди прочитали б мутований код як\n" +
      "оригінал і чесно показали б ✅ на ньому. Розберіться з причиною і запустіть знову.");
    break;
  }
}

