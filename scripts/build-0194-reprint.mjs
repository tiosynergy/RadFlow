import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const md5 = (s) => createHash("md5").update(s, "utf8").digest("hex");

const SRC_MIG = "supabase/migrations/0193_definer_room_gate.sql";
