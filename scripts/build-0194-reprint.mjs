// ⚠️ БАЗИС НА САМІ ФРАГМЕНТИ: dryrun без DRYRUN-ONLY-ділянок і без першого
//    рядка мусить бути ПОБАЙТОВО накатом. Це те саме правило, що перевіряє
//    тест, — але тут воно спрацює раніше, ніж я запущу фрагмент на проді.
const stripDry = (s) => s
  .split("\n").slice(1).join("\n")
  // ⚠️ Ділянка вирізається РАЗОМ із власним переводом рядка на початку й у
  //    кінці, і на її місце НЕ ставиться нічого. Перша редакція підставляла
  //    "\n" — і різниця виїхала на один зайвий перевід рядка (байт 10306).
  //    Це не косметика: правило мусить бути ТОЧНИМ, бо той самий рядок коду
  //    стоїть у тесті, і «майже точне» правило дало б там зелень на різних
  //    фрагментах.
  .replace(/\n *-- >>> DRYRUN-ONLY:[\s\S]*?\n *-- <<< DRYRUN-ONLY\n/g, "");
if (stripDry(DRYRUN) !== stripDry(APPLY)) {
  const a = stripDry(APPLY), d = stripDry(DRYRUN);
  let i = 0; while (i < a.length && a[i] === d[i]) i++;
  throw new Error(`DRYRUN ≢ НАКАТ після зняття маркерів; перша різниця на байті ${i}:\n`
    + `  накат:  ${JSON.stringify(a.slice(i, i + 120))}\n  dryrun: ${JSON.stringify(d.slice(i, i + 120))}`);
}
// і симетрично: у НАКАТІ не має бути ні одного маркера й ні одного зонда.
// ⚠️ РАХУЄМО ПО КОДУ, А НЕ ПО ФАЙЛУ. Перша редакція чекала рівно два
//    \`invariants_check(false)\` — і впала, бо третє входження сидить у
//    КОМЕНТАРІ преамбули («заміряно 9,4 с за прогін»). Це вже четвертий раз
//    за два пакети, коли асерт ловить власне пояснення: детектор на SQL
//    спершу ріже коментарі, і тільки потім рахує.
const APPLY_CODE = APPLY.replace(/--[^\n]*/g, "");
for (const [needle, want] of [["DRYRUN-ONLY", 0], ["_p0194_before", 0],
                              ["DRYRUN_0194_ROLLBACK", 0], ["invariants_check(false)", 2]]) {
  const n = APPLY_CODE.split(needle).length - 1;
  if (n !== want) throw new Error(`НАКАТ (код без коментарів): «${needle}» трапляється ${n} раз(ів), а треба ${want}`);
}

