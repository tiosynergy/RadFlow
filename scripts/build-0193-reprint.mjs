//    Різниця з 0104/0105 — РІВНО один кон'юнкт у `where`, названий у шапці.
// ---------------------------------------------------------------------------
// Предстан двох RPC — БЕРЕМО З ФАЙЛІВ 0104/0105 і доводимо збіг із проДом.
// ⚠️ Нові тіла НЕ передруковуються руками: перша редакція збирача набирала їх
//    із виводу прода (нормалізованого!), і третій базис це зловив — перенос
//    зіпсував відступи й склейку рядків. Тепер нове тіло = старе + ОДИН рядок,
//    тобто «відрізняється рівно одним кон'юнктом» правдиве ЗА ПОБУДОВОЮ.
function body2(file) {
  const txt = readFileSync(file, "utf8").replace(/\r/g, "");
  const o = "\nas $$";
  const c = "\n$$;";
  const a = txt.indexOf(o);
  const b = txt.indexOf(c, a);
  if (a < 0 || b < 0) throw new Error(`${file}: не знайдено межі тіла`);
  if (txt.indexOf(o, a + 1) >= 0) throw new Error(`${file}: \`as $$\` не один`);
  return txt.slice(a + o.length, b + 1);
}

