const GATE = "       and ((select public.auth_role()) is distinct from 'radiologist'\n"
  + "            or public.auth_radiologist_room_ok(w.room_id))\n";
const ANCHOR = "     where w.clinic_id = v_clinic\n";
function withGate(old, name) {
  const hits = old.split(ANCHOR).length - 1;
  if (hits !== 1) throw new Error(`${name}: якір \`where w.clinic_id\` трапляється ${hits} раз(ів)`);
  return old.replace(ANCHOR, ANCHOR + GATE);
}

